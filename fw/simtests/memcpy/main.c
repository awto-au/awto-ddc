static const unsigned int LEN[5] = {0, 1, 255, 256, 300};
static const unsigned int LEN_IDATA[3] = {0, 1, 64};

/* dst = xd+1 (XDATA), guards xd[0] and xd[n+1] must stay 0xEE */
static unsigned char chk_dst(void *r, unsigned int n)
{
    unsigned char bad = 0;
    if (r != (void *)(xd + 1)) bad++;
    if (xd[0] != 0xEE || xd[n + 1] != 0xEE) bad++;
    return bad;
}

static unsigned char run_xx(unsigned int n)
{
    unsigned int i;
    unsigned char bad;
    void *r;
    for (i = 0; i < MAXN + 8; i++) { xd[i] = 0xEE; xs[i] = (unsigned char)(i * 5 + 9); }
    r = __memcpy(xd + 1, xs + 2, n);
    bad = chk_dst(r, n);
    for (i = 0; i < n; i++) if (xd[1 + i] != xs[2 + i]) bad++;
    return bad;
}

static unsigned char run_cx(unsigned int n)
{
    unsigned int i;
    unsigned char bad;
    void *r;
    for (i = 0; i < MAXN + 8; i++) xd[i] = 0xEE;
    r = __memcpy(xd + 1, cs, n);
    bad = chk_dst(r, n);
    for (i = 0; i < n; i++) if (xd[1 + i] != cs[i]) bad++;
    return bad;
}

static unsigned char run_ix(unsigned int n)
{
    unsigned int i;
    unsigned char bad;
    void *r;
    for (i = 0; i < MAXN + 8; i++) xd[i] = 0xEE;
    for (i = 0; i < 64; i++) is[i] = (unsigned char)(i * 3 + 1);
    r = __memcpy(xd + 1, is, n);
    bad = chk_dst(r, n);
    for (i = 0; i < n; i++) if (xd[1 + i] != is[i]) bad++;
    return bad;
}

void main(void)
{
    unsigned char i, b, tot;
    tot = 0;
    for (i = 0; i < 5; i++) { b = run_xx(LEN[i]); tot += b; sim_val("xx", ((unsigned long)LEN[i] << 8) | b); }
    for (i = 0; i < 5; i++) { b = run_cx(LEN[i]); tot += b; sim_val("cx", ((unsigned long)LEN[i] << 8) | b); }
    for (i = 0; i < 3; i++) { b = run_ix(LEN_IDATA[i]); tot += b; sim_val("ix", ((unsigned long)LEN_IDATA[i] << 8) | b); }
    sim_val("bad", tot);
    sim_done();
}
