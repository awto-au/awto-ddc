#!/usr/bin/env python3
"""Generate the firmware EDID byte tables (awto_edid_dp.h / awto_edid_hdmi.h) for one unit.

usage: fw_edid_tables.py --serial AWT26110003 [--out DIR]
  runs make_edid.py for that serial, writes C initialiser lists included by the overlay EdidTableD1-3.h
  (D1 = DP, D2/D3 = HDMI). Default DIR: the ported tree's Kernel/User Common Function/Header/EDID.
  Run after `keil2sdcc.py port` (port regenerates the tree). Log: ./tmp/logs/fw_edid_tables.log
"""
import argparse, subprocess, sys, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sdcc_overlay import repo_root  # noqa: E402

ROOT = repo_root()
MAKE_EDID_TIMEOUT = 60      # make_edid + edid-decode run in ~1 s; stall guard only


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--serial", required=True)
    ap.add_argument("--out", default=str(ROOT / "tmp/sdcc-port/src/Kernel/User Common Function/Header/EDID"))
    a = ap.parse_args()
    (ROOT / "tmp/logs").mkdir(parents=True, exist_ok=True)
    log = (ROOT / "tmp/logs/fw_edid_tables.log").open("a")
    work = ROOT / "tmp/fw-edid" / a.serial
    work.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([sys.executable, str(ROOT / "scripts/make_edid.py"), "--out", str(work), "--serial", a.serial],
                       capture_output=True, text=True, timeout=MAKE_EDID_TIMEOUT)
    log.write(f"{time.strftime('%Y-%m-%dT%H:%M:%S%z')} make_edid {a.serial} rc={r.returncode}\n{r.stdout}{r.stderr}\n")
    if r.returncode:
        sys.exit(f"make_edid.py failed:\n{r.stdout}{r.stderr}")
    out = Path(a.out)
    for kind in ("dp", "hdmi"):
        b = (work / f"awto-{kind}.bin").read_bytes()
        if len(b) != 256:
            sys.exit(f"awto-{kind}.bin is {len(b)} B, expected 256")
        rows = [", ".join(f"0x{x:02X}" for x in b[i:i + 16]) + "," for i in range(0, 256, 16)]
        (out / f"awto_edid_{kind}.h").write_text(f"// generated by scripts/fw_edid_tables.py --serial {a.serial}\n"
                                                + "\n".join(rows) + "\n")
        print(f"wrote {out / f'awto_edid_{kind}.h'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
