#!/usr/bin/env python3
"""Generate docs/audio-registers.md: audio build options + DAC/DVC register fields, Dahua vs ours.

Sources (cited in the output): SDK option headers of a tree, regdb field descriptions,
a Dahua-firmware register dump and a dump of ours (tmp/regs/*.json, `pages` format).
"""
import argparse
import gzip
import json
import os
import re
import subprocess
import sys
from pathlib import Path


def _repo() -> Path:
    env = os.environ.get("AWTO_DDC_REPO")
    if env:
        return Path(env)
    try:
        return Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True,
                                            cwd=Path(__file__).parent).strip())
    except (OSError, subprocess.CalledProcessError):
        return Path(__file__).resolve().parent.parent


REPO = _repo()
LOG = REPO / "tmp/logs/audio_regs_doc.log"
RANGES = [(0x06C0, 0x06F0), (0x08A0, 0x08B0), (0x6F00, 0x6F02)]   # DAC/analog, DVC, audio mux
OPT_RE = re.compile(r"#define\s+(_[A-Z0-9_]*(?:AUDIO|DAC|LINE_IN|DVC)[A-Z0-9_]*)\s+(\S+)\s*(?://\s*(.*))?")
DEFAULT_H = "fw/sdk/Kernel/Common/RL6449_Project_Default.h"
PROJECT_H = "fw/sdk/Project/Header/RL6449_Project.h"


def log(msg: str) -> None:
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with LOG.open("a") as f:
        f.write(msg + "\n")
    print(msg, file=sys.stderr)


def options(path: Path) -> dict:
    out = {}
    for ln in path.read_text(errors="replace").splitlines():
        m = OPT_RE.match(ln.strip())
        if m and m.group(1) not in out:
            out[m.group(1)] = (m.group(2), (m.group(3) or "").strip())
    return out


def page_bytes(dump: dict, addr: int):
    pg = dump["pages"].get(f"{addr >> 8:02X}")
    if pg is None:
        return None
    lo = addr & 0xFF
    if isinstance(pg, list):
        return pg[lo] if lo < len(pg) else None
    for start, hx in pg.items():                       # {"C0": "db f1 ..."}
        s, b = int(start, 16), bytes.fromhex(hx.replace(" ", ""))
        if s <= lo < s + len(b):
            return b[lo - s]
    return None


def regdb():
    regs, fields = {}, {}
    with gzip.open(REPO / "re/regdb/RTD2795T-CG.tsv.gz", "rt") as f:
        for ln in f:
            c = ln.rstrip("\n").split("\t")
            if len(c) < 11:
                continue
            try:
                a = int(c[1], 16)
            except ValueError:
                continue
            if not any(lo <= a < hi for lo, hi in RANGES):
                continue
            if c[4] == "REG":
                regs.setdefault(a, (c[5], c[10]))
            elif c[4] == "FIELD":
                desc = (c[16] if len(c) > 16 else "").replace("\\n", "; ").replace("|", "/").strip("; ")
                fields.setdefault(a, []).append((int(c[6]), int(c[7]), c[8], c[9], desc))
    return regs, fields


def fv(byte, msb, lsb):
    return None if byte is None else (byte >> lsb) & ((1 << (msb - lsb + 1)) - 1)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tree", type=Path, default=REPO, help="worktree whose option headers are documented")
    ap.add_argument("--dahua", type=Path, required=True, help="register dump taken under the Dahua firmware")
    ap.add_argument("--ours", type=Path, required=True, help="register dump of our firmware")
    ap.add_argument("--out", type=Path, default=REPO / "docs/audio-registers.md")
    a = ap.parse_args()
    dflt, proj = options(a.tree / DEFAULT_H), options(a.tree / PROJECT_H)
    dh, ou = json.loads(a.dahua.read_text()), json.loads(a.ours.read_text())
    regs, fields = regdb()
    head = subprocess.run(["git", "-C", str(a.tree), "log", "-1", "--format=%h %cs"], capture_output=True, text=True).stdout.strip()
    L = ["# Audio: build options and registers (generated)", "",
         f"- Generated by `scripts/audio_regs_doc.py`; do not edit by hand. Behaviour, tests, decisions: [audio.md](audio.md).",
         f"- Options: `{DEFAULT_H}` (SDK default) and `{PROJECT_H}` (ours), tree `{a.tree.name}` at {head}.",
         f"- Registers: field names and descriptions from `re/regdb/RTD2795T-CG.tsv.gz`.",
         f"- Dahua firmware values: `{a.dahua.relative_to(REPO) if a.dahua.is_relative_to(REPO) else a.dahua}` ({dh.get('time', '?')}, unit {dh.get('serial', '?')}).",
         f"- Our values: `{a.ours.relative_to(REPO) if a.ours.is_relative_to(REPO) else a.ours}` ({ou.get('time', '?')}, {ou.get('image', '?')}).",
         "- **bold** = Dahua and ours differ. Blank = not in that dump.", "",
         "## Build options", "", "| option | SDK default | ours | header comment |", "|---|---|---|---|"]
    for name in sorted(set(dflt) | set(proj)):
        d, p = dflt.get(name, ("-", ""))[0], proj.get(name, (None, ""))[0]
        ours = p if p is not None else d
        cmt = (proj.get(name) or dflt.get(name))[1].replace("|", "/")
        mark = "**" if p is not None and p != d else ""
        L.append(f"| `{name}` | {d} | {mark}{ours}{mark} | {cmt} |")
    L += ["", "## Registers", "", "| addr | register | reset | Dahua | ours |", "|---|---|---|---|---|"]
    for a_ in sorted(regs):
        nm, rst = regs[a_]
        bd, bo = page_bytes(dh, a_), page_bytes(ou, a_)
        sd = "" if bd is None else f"{bd:02X}"
        so = "" if bo is None else f"{bo:02X}"
        mark = "**" if sd and so and sd != so else ""
        L.append(f"| {a_:04X} | {nm} | {rst} | {mark}{sd}{mark} | {mark}{so}{mark} |")
    L += ["", "## Register fields", "", "| addr | bits | field | RW | Dahua | ours | description |", "|---|---|---|---|---|---|---|"]
    for a_ in sorted(fields):
        bd, bo = page_bytes(dh, a_), page_bytes(ou, a_)
        for msb, lsb, fn, rw, desc in sorted(fields[a_], reverse=True):
            if fn.lower() in ("reserved", "dummy"):
                continue
            vd, vo = fv(bd, msb, lsb), fv(bo, msb, lsb)
            sd = "" if vd is None else f"{vd:X}"
            so = "" if vo is None else f"{vo:X}"
            mark = "**" if sd and so and sd != so else ""
            bits = f"{msb}" if msb == lsb else f"{msb}:{lsb}"
            L.append(f"| {a_:04X} | {bits} | {fn} | {rw} | {mark}{sd}{mark} | {mark}{so}{mark} | {desc[:160]} |")
    a.out.write_text("\n".join(L) + "\n")
    log(f"wrote {a.out}: {len(set(dflt) | set(proj))} options, {len(regs)} registers, {sum(map(len, fields.values()))} fields")
    return 0


if __name__ == "__main__":
    sys.exit(main())
