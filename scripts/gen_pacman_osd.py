#!/usr/bin/env python3
"""Generate fw/test/pacman_osd_data.inc from the Pac-Man OSD prototype (tools/pacman_osd, awto-ddc#227 side project).

usage: gen_pacman_osd.py [--check]
  Reads tools/pacman_osd/generated/glyphs.bin (343 glyphs x 9 words x 3 bytes, as the prototype's pm_hw_word writes them),
  generated/manifest.json (palette, layout) and preview/8051-capture.json (initial cell commands, 96 frames of cell updates).
  Writes the include: palette, glyph bytes, initial cells (B0 B1 B2 per cell), frame table (offset per frame) + delta stream
  (cell index lo, hi, B0, B1, B2 per update). --check: exit 1 if the include on disk differs.
Log: ./tmp/logs/gen_pacman_osd.log
"""
import argparse
import json
import os
import sys
import isostamp  # noqa: E402
from pathlib import Path

ROOT = Path(os.environ.get("AWTO_DDC_REPO") or Path(__file__).resolve().parent.parent)
SRC = ROOT / "tools/pacman_osd"
OUT = ROOT / "fw/test/pacman_osd_data.inc"
LOG = ROOT / "tmp/logs/gen_pacman_osd.log"
BANK = 11                                   # bank the loader and the data share (movc: same bank, like qc_osd.c in bank 12)


def say(s: str) -> None:
    LOG.parent.mkdir(parents=True, exist_ok=True)
    line = f"{isostamp.now()} {s}"
    with LOG.open("a") as f:
        f.write(line + "\n")
    print(line, flush=True)


def arr(name: str, data: bytes, per: int = 16) -> str:
    rows = []
    for i in range(0, len(data), per):
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + per]) + ",")
    return f"static const uint8_t __code {name}[{len(data)}] = {{\n" + "\n".join(rows) + "\n};\n"


def build() -> str:
    m = json.loads((SRC / "generated/manifest.json").read_text())
    cap = json.loads((SRC / "preview/8051-capture.json").read_text())
    glyphs = (SRC / "generated/glyphs.bin").read_bytes()
    assert len(glyphs) == m["glyph_count"] * 9 * 3, "glyphs.bin size"
    cells = b"".join(bytes(c) for c in cap["initial"])
    assert len(cells) == m["cols"] * m["rows"] * 3
    stream = bytearray()
    index = []
    for f in cap["frames"]:
        index.append(len(stream))
        for pos, b0, b1, b2 in f["delta"]:
            stream += bytes([pos & 0xFF, pos >> 8, b0, b1, b2])
    index.append(len(stream))
    idx = b"".join(bytes([v & 0xFF, v >> 8]) for v in index)
    pal = b"".join(bytes(c) for c in m["palette"])
    head = ("/* pacman_osd_data.inc: GENERATED by scripts/gen_pacman_osd.py from tools/pacman_osd. Do not edit.\n"
            " * Read by fw/test/pacman_osd.c via movc: same bank. */\n"
            f"#pragma place bank({BANK})\n"
            f"#define AWTO_PM_COLS            {m['cols']}\n#define AWTO_PM_ROWS            {m['rows']}\n"
            f"#define AWTO_PM_GLYPHS          {m['glyph_count']}\n#define AWTO_PM_FS_BASE         {m['fs_base']}\n"
            f"#define AWTO_PM_FONT_BASE       {m['font_base']}\n#define AWTO_PM_FRAMES          {len(cap['frames'])}\n"
            f"#define AWTO_PM_PAL_N           {len(m['palette'])}\n")
    return (head + arr("g_pmPal", pal, 3) + arr("g_pmGlyph", glyphs, 27) + arr("g_pmCell", cells, 12)
            + arr("g_pmFrameIdx", idx, 16) + arr("g_pmDelta", bytes(stream), 15))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        say(f"{OUT} {'up to date' if ok else 'STALE: run scripts/gen_pacman_osd.py'}")
        return 0 if ok else 1
    OUT.write_text(text)
    say(f"wrote {OUT} ({len(text)} bytes of source)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
