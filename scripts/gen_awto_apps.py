#!/usr/bin/env python3
"""Generate the extra-app dispatch table (apps_gen.inc) from the AWTO_APP(...) macros of an extra source root (docs/extra-apps.md).

usage: gen_awto_apps.py ROOT [--out FILE] [--check]
  ROOT: extra source root (./dev.py build --extra-fw ROOT); every **/*.c is scanned for
        AWTO_APP(name, init, step, key, stop)    (a hook = a function name, or AWTO_APP_NONE / 0 / NULL for none)
  --out: default tmp/sdcc-port/apps_gen.inc (derived artifact: regenerated each build, never tracked); apps_gen.tsv beside it = index, name, source
  --check: exit 1 when --out is missing or differs from what ROOT generates
Output: AWTO_APP_COUNT and the switch dispatchers AwtoAppDoInit / Step / Key / Stop (direct calls, no function
  pointers: SDCC banking reaches a banked function only through the stub of a direct call). Order = sorted by file path, then position.
Log: ./tmp/logs/gen_awto_apps.log
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _log import log_line as _log_line
from _repo import repo_root

REPO = repo_root()

LOG = REPO / "tmp/logs/gen_awto_apps.log"
OUT = REPO / "tmp/sdcc-port/apps_gen.inc"
APP_MAX = 15                                  # VCP 0xEB values 0x20 + index; the sync-log value keeps the index in 4 bits
NONE = ("AWTO_APP_NONE", "0", "NULL")
IDENT = re.compile(r"[A-Za-z_]\w*")
CALL = re.compile(r"\bAWTO_APP\s*\(")
HOOKS = ("init", "step", "key", "stop")
PROTO = {"init": "void {f}(void)", "step": "void {f}(void)", "key": "void {f}(BYTE ucKey, BYTE ucEv)", "stop": "void {f}(void)"}


def log(s):
    _log_line(s, LOG)


def strip_comments(t: str) -> str:
    """Comments and string literals blanked (same length): a macro in a comment is not an app."""
    t = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), t, flags=re.DOTALL)
    t = re.sub(r"//[^\n]*", lambda m: " " * len(m.group(0)), t)
    return re.sub(r'"(?:\\.|[^"\\\n])*"', lambda m: '"' + " " * (len(m.group(0)) - 2) + '"', t)


def scan(root: Path) -> list[dict]:
    """[{name, init, step, key, stop, file, line}] in file / position order. ValueError: a malformed or duplicate AWTO_APP."""
    apps = []
    for p in sorted(root.rglob("*.c")):
        text = strip_comments(p.read_text(errors="replace"))
        for m in CALL.finditer(text):
            line = text.count("\n", 0, m.start()) + 1
            if re.match(r"\s*#\s*define", text[text.rfind("\n", 0, m.start()) + 1:m.start()]):
                continue                                          # the macro's own definition
            where = f"{p}:{line}"
            depth, i = 1, m.end()
            while i < len(text) and depth:                        # balanced parentheses: a malformed argument is an error, not a skipped app
                depth += {"(": 1, ")": -1}.get(text[i], 0)
                i += 1
            if depth:
                raise ValueError(f"{where}: AWTO_APP is not closed")
            args = [a.strip() for a in text[m.end():i - 1].split(",")]
            if len(args) != 1 + len(HOOKS):
                raise ValueError(f"{where}: AWTO_APP takes name, init, step, key, stop (got {len(args)} arguments)")
            bad = [a for a in args if not IDENT.fullmatch(a) and a != "0"]
            if bad:
                raise ValueError(f"{where}: AWTO_APP argument {bad[0]!r} is not an identifier")
            app = {"name": args[0], "file": str(p), "line": line}
            for h, a in zip(HOOKS, args[1:]):
                app[h] = None if a in NONE else a
            if app["name"] in NONE:
                raise ValueError(f"{where}: AWTO_APP name {app['name']!r} is reserved")
            apps.append(app)
    names = [a["name"] for a in apps]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise ValueError(f"duplicate AWTO_APP name(s): {', '.join(dup)}")
    if len(apps) > APP_MAX:
        raise ValueError(f"{len(apps)} apps: at most {APP_MAX} (VCP 0xEB 0x20 + index)")
    return apps


def render(apps: list[dict], root: Path) -> str:
    out = [f"/* generated by scripts/gen_awto_apps.py from {root}: do not edit */",
           f"#define AWTO_APP_COUNT {len(apps)}"]
    for h in HOOKS:
        for f in sorted({a[h] for a in apps if a[h]}):
            out.append(f"extern {PROTO[h].format(f=f)};")
    for h in HOOKS:
        key = h == "key"
        out.append(f"static void AwtoAppDo{h.capitalize()}(BYTE ucI{', BYTE ucKey, BYTE ucEv' if key else ''})")
        out.append("{")
        out.append("    ucI = ucI;" + ("\n    ucKey = ucKey;\n    ucEv = ucEv;" if key else ""))
        out.append("    switch(ucI)")
        out.append("    {")
        for i, a in enumerate(apps):
            if a[h]:
                out.append(f"        case {i}:\n            {a[h]}({'ucKey, ucEv' if key else ''});\n            break;")
        out.append("        default:\n            break;\n    }")
        out.append("}")
    has = [f"(ucI == {i})" for i, a in enumerate(apps) if a["key"]]
    out.append("static BYTE AwtoAppHasKey(BYTE ucI)")
    out.append("{")
    out.append(f"    return {' || '.join(has) if has else '0'};" if has else "    ucI = ucI;\n    return 0;")
    out.append("}")
    return "\n".join(out) + "\n"


def tsv(apps: list[dict]) -> str:
    return "".join(f"{i}\t{a['name']}\t{a['file']}:{a['line']}\n" for i, a in enumerate(apps))


def generate(root: Path, out: Path = OUT) -> list[dict]:
    apps = scan(root)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = render(apps, root)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    out.with_suffix(".tsv").write_text(tsv(apps))                 # index, name, source (host tools; the firmware carries no names)
    log(f"{out}: {len(apps)} app(s) from {root}: {', '.join(a['name'] for a in apps) or 'none'}")
    return apps


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", type=Path)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    root = a.root.resolve()
    if not root.is_dir():
        log(f"FAIL: {root} is not a directory")
        return 2
    try:
        if a.check:
            text = render(scan(root), root)
            ok = a.out.exists() and a.out.read_text() == text
            log(f"{'up to date' if ok else 'FAIL: out of date or missing'}: {a.out}")
            return 0 if ok else 1
        generate(root, a.out)
    except ValueError as e:
        log(f"FAIL: {e}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
