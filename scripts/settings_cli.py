#!/usr/bin/env python3
"""Settings registry on a running unit or the sim (awto-ddc#67): list | get NAME|ID | set NAME|ID VALUE | defaults | save.

usage: settings_cli.py (--bus N --serial S | --sim BIN) --map MAP CMD [ARGS] [--no-confirm]
  Rows: scripts/settings_table.py (GENERATED by settings_gen.py from awto-rtdfw settings/registry.tsv).
  Transport: the firmware mailbox `_vcp_box` (awto-rtdfw vcp.c) over debug slave 0x35, byte reads/writes of XDATA
  (W 0x01 hi, W 0x3A lo, R 0x08 / W 0x01 hi, W 0x03 val, W 0x3B lo). Same get/set as DDC/CI: MCCS code per row, or
  0xE0 (id select) + 0xE1 (value) for every row.
  set: a risky row is confirmed (VCP 0xE3 = 1) only after the value reads back; if the link dies first, the firmware
  reverts it after 15 s. --no-confirm leaves it pending (test the auto-revert).
  VALUE: number, or an option label for enums (case-insensitive), or on/off for bools.
Log: ./tmp/logs/settings_cli.log
"""
from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import settings_table as T

ROOT = Path(__file__).resolve().parents[1]
LOG = ROOT / "tmp/logs/settings_cli.log"
DBG = 0x6A                           # debug slave 0x35, 8-bit address
SEL, VAL, SCHEMA, CMD = 0xE0, 0xE1, 0xE2, 0xE3
BOX = dict(magic=0, cmd=1, code=2, result=3, val_lo=4, val_hi=5, cur_lo=6, cur_hi=7, max_lo=8, max_hi=9, type=10, seq=11)
POLLS = 40                           # mailbox answer: main loop serves it every pass (~3 ms); one poll = 3 I2C transfers
# hardware: the main loop can be blocked by an OSD draw (input-info pop-up 375 ms, #60); 1.25 x -> 0.47 s, then FAIL
MAILBOX_S = 0.47


def say(s: str):
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with LOG.open("a") as f:
        f.write(time.strftime("%Y-%m-%dT%H:%M:%S%z ") + s + "\n")
    print(s, flush=True)


def xaddr(map_text: str, name: str) -> int:
    m = re.search(rf"([0-9A-F]{{8}})\s+_{name}\b", map_text)
    if not m:
        raise SystemExit(f"_{name} not in the map (image without the settings registry, #67?)")
    return int(m.group(1), 16) & 0xFFFF


class Box:
    """The firmware's VCP mailbox over a debug-slave transport (rtd_i2c_bridge.Real or fw_sim.SimBus)."""

    def __init__(self, bus, map_text: str, sim=False):
        self.bus, self.base, self.sim = bus, xaddr(map_text, "vcp_box"), sim

    def wr(self, off: int, v: int):
        a = self.base + off
        ok = self.bus.write(DBG, 0x01, bytes([a >> 8])) and self.bus.write(DBG, 0x03, bytes([v & 0xFF])) and \
            self.bus.write(DBG, 0x3B, bytes([a & 0xFF]))
        if not ok:
            raise SystemExit(f"debug-slave write 0x{a:04X} NAK")

    def rd(self, off: int) -> int:
        a = self.base + off
        if not (self.bus.write(DBG, 0x01, bytes([a >> 8])) and self.bus.write(DBG, 0x3A, bytes([a & 0xFF]))):
            raise SystemExit(f"debug-slave read 0x{a:04X} NAK")
        r = self.bus.read(DBG, 0x08, 1)
        if not r:
            raise SystemExit(f"debug-slave read 0x{a:04X}: no data")
        return r[0]

    def xrd(self, addr: int, n: int) -> bytes:
        """n XDATA bytes: byte reads over the debug slave; in the sim straight from the model (fast, same bytes)"""
        if self.sim:
            return bytes(self.bus.m.rd(addr, n))
        out = bytearray()
        for a in range(addr, addr + n):
            if not (self.bus.write(DBG, 0x01, bytes([a >> 8])) and self.bus.write(DBG, 0x3A, bytes([a & 0xFF]))):
                raise SystemExit(f"debug-slave read 0x{a:04X} NAK")
            r = self.bus.read(DBG, 0x08, 1)
            if not r:
                raise SystemExit(f"debug-slave read 0x{a:04X}: no data")
            out += r
        return bytes(out)

    def xwr(self, addr: int, data: bytes):
        """Write XDATA bytes over the debug slave; used for firmware controls outside the VCP mailbox."""
        if self.sim:
            self.bus.m.wr(addr, data)
            return
        for a, v in zip(range(addr, addr + len(data)), data):
            ok = self.bus.write(DBG, 0x01, bytes([a >> 8])) and self.bus.write(DBG, 0x03, bytes([v])) and \
                self.bus.write(DBG, 0x3B, bytes([a & 0xFF]))
            if not ok:
                raise SystemExit(f"debug-slave write 0x{a:04X} NAK")

    def call(self, cmd: int, code: int, v: int = 0) -> tuple[int, int, int]:
        """(cur, max, type); raises on an unsupported code or no answer"""
        if self.rd(BOX["magic"]) != ord("V"):
            raise SystemExit("mailbox magic missing: firmware has not run vcp_box_service (old image or not booted)")
        seq = self.rd(BOX["seq"])
        self.wr(BOX["code"], code)
        self.wr(BOX["val_lo"], v & 0xFF)
        self.wr(BOX["val_hi"], v >> 8 & 0xFF)
        self.wr(BOX["cmd"], cmd)
        t0 = time.monotonic()
        for k in range(POLLS if self.sim else 1 << 30):
            if self.sim:
                self.bus.wait(0.01)
            elif time.monotonic() - t0 > MAILBOX_S:
                k = -1
                break
            if self.rd(BOX["cmd"]) == 0 and self.rd(BOX["seq"]) != seq:
                break
        else:
            k = -1
        if k < 0:
            raise SystemExit(f"mailbox: no answer to cmd {cmd} code 0x{code:02X} after {k if k >= 0 else 'all'} polls "
                             f"({time.monotonic() - t0:.2f} s host time)")
        if not self.rd(BOX["result"]):
            if cmd == 3:
                raise SystemExit(f"menu command {code} arg {v}: refused")
            raise SystemExit(f"VCP 0x{code:02X}: unsupported (no such row or code)")
        g = lambda o: self.rd(BOX[o + "_lo"]) | self.rd(BOX[o + "_hi"]) << 8
        return g("cur"), g("max"), self.rd(BOX["type"])

    def get_row(self, r: dict) -> int:
        self.call(2, SEL, r["id"])
        return self.call(1, VAL)[0]

    def set_row(self, r: dict, v: int, confirm=True) -> int:
        self.call(2, SEL, r["id"])
        got = self.call(2, VAL, v)[0]
        if "risky" in r["flags"] and confirm and got == v:
            self.call(2, CMD, 1)
        return got

    def schema(self) -> int:
        return self.call(1, SCHEMA)[0]


def row_of(key: str) -> dict:
    r = T.BY_ID.get(int(key)) if key.isdigit() else T.BY_NAME.get(key)
    if r is None:
        raise SystemExit(f"no setting {key!r}: `list` shows the names")
    return r


def parse_value(r: dict, s: str) -> int:
    if r["type"] == "bool" and s.lower() in ("on", "off", "true", "false"):
        return int(s.lower() in ("on", "true"))
    if r["type"] == "enum" and not re.fullmatch(r"-?\d+", s):
        for i, o in enumerate(r["options"]):
            if o.lower() == s.lower():
                return r["min"] + i
        raise SystemExit(f"{r['name']}: {s!r} is not one of {r['options']}")
    v = int(s, 0)
    if not r["min"] <= v <= r["max"]:
        raise SystemExit(f"{r['name']}: {v} outside {r['min']}..{r['max']}")
    return v


def show(r: dict, v: int) -> str:
    if r["type"] == "bool":
        t = "on" if v else "off"
    elif r["type"] == "enum" and 0 <= v - r["min"] < len(r["options"]):
        t = r["options"][v - r["min"]]
    elif r["unit"] == "dhz":
        t = f"{v / 10:.1f} Hz"
    else:
        t = f"{v} {dict(percent='%', ms='ms', s='s', hz='Hz').get(r['unit'], '')}".strip()
    return f"{r['name']} = {t} (raw {v})"


def open_bus(a):
    if a.sim:
        import fw_sim
        bus = fw_sim.SimBus(a.sim, Path(a.map))
        return bus, True
    import i2cbus
    from rtd_i2c_bridge import Real
    i2cbus.require_unit(a.bus, a.serial)
    return Real(a.bus, allow_write=True), False


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bus", type=int)
    ap.add_argument("--serial")
    ap.add_argument("--sim", type=Path)
    ap.add_argument("--map", required=True)
    ap.add_argument("--no-confirm", action="store_true")
    ap.add_argument("cmd", choices=["list", "get", "set", "defaults", "save", "rows"])
    ap.add_argument("args", nargs="*")
    a = ap.parse_args()
    if a.cmd == "rows":                                  # offline: the table, no unit
        for r in T.ROWS:
            print(f"{r['id']:3} {r['name']:18} {r['group']:8} {r['type']:6} {r['min']}..{r['max']} def {r['default']} "
                  f"{','.join(r['flags'])}")
        return 0
    if not a.sim and (a.bus is None or not a.serial):
        raise SystemExit("need --bus N --serial S (dev.py settings --unit N fills them) or --sim BIN")
    bus, sim = open_bus(a)
    box = Box(bus, Path(a.map).read_text(errors="replace"), sim)
    sch = box.schema()
    if sch != T.SCHEMA:
        say(f"WARN firmware settings schema 0x{sch:04X}, host table 0x{T.SCHEMA:04X}: regenerate or flash the matching image")
    if a.cmd == "list":
        for r in T.ROWS:
            if r["type"] != "action":
                say(show(r, box.get_row(r)))
    elif a.cmd == "get":
        for k in a.args:
            say(show(row_of(k), box.get_row(row_of(k))))
    elif a.cmd == "set":
        if len(a.args) != 2:
            raise SystemExit("set NAME VALUE")
        r = row_of(a.args[0])
        v = parse_value(r, a.args[1])
        got = box.set_row(r, v, not a.no_confirm)
        say(("set " if got == v else f"REFUSED (firmware kept {got}): ") + show(r, got))
        return 0 if got == v else 1
    elif a.cmd == "defaults":
        box.call(2, CMD, 3)
        say("all settings to defaults (VCP 0xE3 = 3)")
    elif a.cmd == "save":
        box.call(2, CMD, 2)
        say("settings record written (VCP 0xE3 = 2)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
