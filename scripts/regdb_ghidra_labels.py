#!/usr/bin/env python3
"""Generate Ghidra EXTMEM register labels + a port-index table from the decoded Realtek register DBs (re/regdb).

usage: regdb_ghidra_labels.py [--chip RTD2795T-CG|consensus] [--exclude names.tsv ...] [--out FILE] [--ports FILE]
- Every scaler register is memory-mapped in XDATA at (page<<8)|reg (SDK ScalerSetByte = *(volatile BYTE xdata*)a).
- Default chip RTD2795T-CG (this unit, all its pages). `consensus` = only addresses in ALL chip DBs with the same name.
- XRAM 0xD700-0xF6FF is RAM: never labelled.
- Duplicate names (mirror pages) get an `_at<addr>` suffix so each label is unique.
- Labels TSV (ApplyRegLabels.java): EXTMEM:<addr> <name> var <comment> [spec]. Hand names (--exclude TSVs) win.
- Port-indexed rows (port_idx set; SDK ScalerSetDataPortByte) share the data-port address. They go to --ports:
  port_addr<TAB>data_addr<TAB>index<TAB>name<TAB>type   (port_addr = data_addr-1, the address-port register).
Log: ./tmp/logs/regdb_ghidra_labels.log
"""
import csv, gzip, os, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(os.environ.get("AWTO_DDC_REPO") or Path(__file__).resolve().parent.parent)
DB = ROOT / "re" / "regdb"
RAM = range(0xD700, 0xF700)
MAX_COMMENT = 240


def load(path):
    """addr -> (register, reset, fields[(hi, lo, name)])"""
    regs, fields = {}, defaultdict(list)
    for r in csv.DictReader(gzip.open(path, "rt", newline=""), delimiter="\t"):
        a = int(r["address"], 0)
        if a in RAM or r["port_idx"]:
            continue
        if r["kind"] == "REG":
            regs.setdefault(a, [r["register"], r["reset"]])
        elif r["kind"] == "FIELD":
            fields[(a, r["register"])].append((int(r["bit_high"]), int(r["bit_low"]), r["field"]))
    return {a: (n, rst, tuple(fields.get((a, n), ()))) for a, (n, rst) in regs.items()}


def paths_for(chip):
    paths = sorted(DB.glob("*.tsv.gz"))
    if chip != "consensus":
        paths = [p for p in paths if p.name == f"{chip}.tsv.gz"]
        if not paths:
            sys.exit(f"no table for {chip} in {DB}")
    return paths


def build(chip):
    tabs = [load(p) for p in paths_for(chip)]
    out = {}
    for a in sorted(set().union(*tabs)):
        ents = [t[a] for t in tabs if a in t]
        if len(ents) != len(tabs) or len({e[0] for e in ents}) != 1:
            continue
        fl = "; ".join(f"[{h}:{l}] {n}" if h != l else f"[{h}] {n}" for h, l, n in ents[0][2]) \
            if len({e[2] for e in ents}) == 1 else ""
        c = f"Realtek RTD register DB ({'all 7 chips agree' if chip == 'consensus' else chip}); reset {ents[0][1] or '?'}."
        if fl:
            c += " Fields: " + fl
        out[a] = (ents[0][0], c[:MAX_COMMENT])
    names = defaultdict(int)
    for n, _ in out.values():
        names[n] += 1
    return {a: (n if names[n] == 1 else f"{n}_at{a:04x}", c) for a, (n, c) in out.items()}


def port_rows(chip):
    """(port_addr, data_addr, index, name, type) for port-indexed REG rows; first chip table only (default) or consensus."""
    rows = None
    for p in paths_for(chip):
        cur = set()
        for r in csv.DictReader(gzip.open(p, "rt", newline=""), delimiter="\t"):
            if r["kind"] == "REG" and r["port_idx"]:
                a = int(r["address"], 0)
                if a not in RAM:
                    cur.add((a - 1, a, int(r["port_idx"], 0), r["register"], r["reg_type"]))
        rows = cur if rows is None else rows & cur
    return sorted(rows)


def hand_named(tsvs):
    s = set()
    for t in tsvs:
        p = Path(t)
        if not p.exists():
            continue
        for ln in p.read_text().splitlines():
            if ln.startswith("EXTMEM:"):
                s.add(int(ln.split("\t")[0][7:], 16))
    return s


def write(chip, exclude, out_path, ports_path=None):
    labels = build(chip)
    skip = hand_named(exclude)
    n = 0
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        f.write("# generated by scripts/regdb_ghidra_labels.py from re/regdb; do not edit\n")
        for a, (name, c) in labels.items():
            if a in skip:
                continue
            f.write(f"EXTMEM:{a:04x}\t{name}\tvar\t{c}\t[spec]\n")
            n += 1
    npt = 0
    if ports_path:
        Path(ports_path).parent.mkdir(parents=True, exist_ok=True)
        with open(ports_path, "w") as f:
            f.write("# port_addr\tdata_addr\tindex\tname\ttype  (generated by regdb_ghidra_labels.py)\n")
            for pa, da, ix, nm, ty in port_rows(chip):
                f.write(f"{pa:04x}\t{da:04x}\t{ix:02x}\t{nm}\t{ty}\n")
                npt += 1
    log = ROOT / "tmp" / "logs" / "regdb_ghidra_labels.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    msg = f"{chip}: {len(labels)} labels, {n} written, {len(labels) - n} skipped (hand-named) -> {out_path}; {npt} port rows"
    print(msg)
    log.open("a").write(msg + "\n")
    return n


if __name__ == "__main__":
    a = sys.argv[1:]
    opt = lambda k, d: a[a.index(k) + 1] if k in a else d
    write(opt("--chip", "RTD2795T-CG"), [a[i + 1] for i, x in enumerate(a) if x == "--exclude"],
          opt("--out", ROOT / "tmp" / "regs_labels.tsv"), opt("--ports", ROOT / "tmp" / "regs_ports.tsv"))
