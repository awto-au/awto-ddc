#!/usr/bin/env python3
"""Generate Ghidra EXTMEM register labels from the decoded Realtek register DBs (re/regdb).

usage: regdb_ghidra_labels.py [--chip RTD2795T-CG|consensus] [--exclude names.tsv ...] [--out FILE]
Output TSV (ApplyRegLabels.java): EXTMEM:<addr> <name> var <comment> [spec]
- consensus (default): only addresses present in ALL chip DBs with the same register name. The unit's exact
  scaler part is unknown [?], so no single chip's names are asserted.
- XDATA pages 0xFD-0xFF only: the only DB pages the firmware's DPTR immediates map to (0xD0-0xE2 is RAM).
- Port-indexed rows (port_idx set) are skipped: several names share one address (one address, one name).
- Addresses already named in an --exclude TSV (hand names) are skipped; hand names win.
Log: ./tmp/logs/regdb_ghidra_labels.log
"""
import csv, gzip, os, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(os.environ.get("AWTO_DDC_REPO") or Path(__file__).resolve().parent.parent)
DB = ROOT / "re" / "regdb"
PAGES = range(0xFD, 0x100)
MAX_COMMENT = 240


def load(path):
    """addr -> (register, reset, fields[(hi, lo, name)])"""
    regs, fields = {}, defaultdict(list)
    for r in csv.DictReader(gzip.open(path, "rt", newline=""), delimiter="\t"):
        a = int(r["address"], 0)
        if (a >> 8) not in PAGES or r["port_idx"]:
            continue
        if r["kind"] == "REG":
            regs.setdefault(a, [r["register"], r["reset"]])
        elif r["kind"] == "FIELD":
            fields[(a, r["register"])].append((int(r["bit_high"]), int(r["bit_low"]), r["field"]))
    return {a: (n, rst, tuple(fields.get((a, n), ()))) for a, (n, rst) in regs.items()}


def build(chip):
    paths = sorted(DB.glob("*.tsv.gz"))
    if chip != "consensus":
        paths = [p for p in paths if p.name == f"{chip}.tsv.gz"]
        if not paths:
            sys.exit(f"no table for {chip} in {DB}")
    tabs = [load(p) for p in paths]
    out = {}
    for a in sorted(set().union(*tabs)):
        ents = [t[a] for t in tabs if a in t]
        if len(ents) != len(tabs) or len({e[0] for e in ents}) != 1:
            continue
        fl = "; ".join(f"[{h}:{l}] {n}" if h != l else f"[{h}] {n}" for h, l, n in ents[0][2]) \
            if len({e[2] for e in ents}) == 1 else ""
        c = f"Realtek RTD register DB ({'all 7 chips agree' if chip == 'consensus' else chip}); reset {ents[0][1] or '?'}."
        if fl:
            c += " Fields: " + fl
        out[a] = (ents[0][0], c[:MAX_COMMENT])
    return out


def hand_named(tsvs):
    s = set()
    for t in tsvs:
        p = Path(t)
        if not p.exists():
            continue
        for ln in p.read_text().splitlines():
            if ln.startswith("EXTMEM:"):
                s.add(int(ln.split("\t")[0][7:], 16))
    return s


def write(chip, exclude, out_path):
    labels = build(chip)
    skip = hand_named(exclude)
    n = 0
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        f.write("# generated by scripts/regdb_ghidra_labels.py from re/regdb; do not edit\n")
        for a, (name, c) in labels.items():
            if a in skip:
                continue
            f.write(f"EXTMEM:{a:04x}\t{name}\tvar\t{c}\t[spec]\n")
            n += 1
    log = ROOT / "tmp" / "logs" / "regdb_ghidra_labels.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    msg = f"{chip}: {len(labels)} labels, {n} written, {len(labels) - n} skipped (hand-named) -> {out_path}"
    print(msg)
    log.open("a").write(msg + "\n")
    return n


if __name__ == "__main__":
    a = sys.argv[1:]
    opt = lambda k, d: a[a.index(k) + 1] if k in a else d
    write(opt("--chip", "consensus"), [a[i + 1] for i, x in enumerate(a) if x == "--exclude"],
          opt("--out", ROOT / "tmp" / "regs_labels.tsv"))
