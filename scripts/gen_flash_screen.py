#!/usr/bin/env python3
"""Generate fw/test/flash_screen_data.inc: the two Pac-Man glyphs (mouth open / closed, 12 x 12 visible rows) of the flash warning screen (#232).

usage: gen_flash_screen.py [--check]
  Glyphs come from gen_pacman_classic.pac_glyph (same shapes as the demo), packed as 1-bit glyphs (9 words = 27 bytes, low byte first).
  --check: exit 1 when the file on disk differs.
Log: ./tmp/logs/gen_flash_screen.log
"""
import argparse
import os
import sys
import isostamp  # noqa: E402
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_pacman_classic as G  # noqa: E402

ROOT = Path(os.environ.get("AWTO_DDC_REPO") or Path(__file__).resolve().parent.parent)
OUT = ROOT / "fw/test/flash_screen_data.inc"
LOG = ROOT / "tmp/logs/gen_flash_screen.log"
RIGHT = 0                       # mouth direction (gen_pacman_classic: right, down, left, up)
OPEN, CLOSED = 3, 0             # opening index of pac_glyph: widest mouth / full disc


def text() -> str:
    glyphs = [G.pack(G.pac_glyph(RIGHT, o), 1) for o in (OPEN, CLOSED)]
    rows = []
    for g in glyphs:
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in g))
    return ("/* Generated by scripts/gen_flash_screen.py: do not edit. Glyph 0 = mouth open, glyph 1 = closed; 27 bytes each (9 words, low byte first). */\n"
            "#define AWTO_FS_GLYPH_BYTES 27\n"
            "#pragma place bank(11)                      // data and its reader (FsByte) share the bank\n"
            "static const __code BYTE g_aucFsGlyph[2 * AWTO_FS_GLYPH_BYTES] = {\n" + ",\n".join(rows) + "};\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    new = text()
    LOG.parent.mkdir(parents=True, exist_ok=True)
    if a.check:
        ok = OUT.exists() and OUT.read_text() == new
        print(f"{isostamp.now()} {OUT.name}: {'current' if ok else 'DIFFERS'}")
        return 0 if ok else 1
    OUT.write_text(new)
    line = f"{isostamp.now()} wrote {OUT}"
    LOG.open("a").write(line + "\n")
    print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
