#!/usr/bin/env python3
"""Colour-temperature preset gains: fw/colour_temp.tsv -> fw/sdk/Panel/RTDColorDefaultTable/ColorTempGains.h (#278).
Usage: colour_temp_gains.py [--check]   (--check: exit 1 if the header is stale). Log: tmp/logs/colour_temp_gains.log"""
import csv
import os
import subprocess
import sys

UNITY = 0x800          # 12-bit gain, 1.0; usColorTempX x contrast / 2048 = contrast coefficient
GAIN_MAX = 0xFFF
HDR = "fw/sdk/Panel/RTDColorDefaultTable/ColorTempGains.h"
SRC = "fw/colour_temp.tsv"


def repo():
    r = os.environ.get("AWTO_DDC_REPO")
    if r:
        return r
    try:
        return subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
    except (subprocess.CalledProcessError, OSError):
        return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rows(root):
    with open(os.path.join(root, SRC)) as f:
        rd = csv.DictReader((ln for ln in f if not ln.startswith("#")), delimiter="\t")
        out = [(r["preset"], [int(r[c], 16) for c in "rgb"]) for r in rd]
    for name, g in out:
        assert all(0 < v <= GAIN_MAX for v in g), f"{name}: gain out of range {g}"
    return out


def render(tbl):
    o = ["// Generated by scripts/colour_temp_gains.py from fw/colour_temp.tsv - do not edit.",
         f"#define _CT_GAIN_UNITY                              0x{UNITY:X}"]
    for name, g in tbl:
        for ch, v in zip(("RED", "GREEN", "BLUE"), g):
            o.append("#define " + f"_CT{name}_{ch}".ljust(44) + f"(0x{v:X})")
    return "\n".join(o) + "\n"


def main():
    root = repo()
    txt = render(rows(root))
    logp = os.path.join(root, "tmp/logs/colour_temp_gains.log")
    os.makedirs(os.path.dirname(logp), exist_ok=True)
    with open(logp, "w") as log:
        log.write(txt)
    print(txt)
    path = os.path.join(root, HDR)
    if "--check" in sys.argv:
        with open(path) as f:
            sys.exit(0 if f.read() == txt else 1)
    with open(path, "w") as f:
        f.write(txt)


main()
