#!/usr/bin/env python3
"""Per-preset RGB gains for the colour-temperature table -> fw/sdk/Panel/RTDColorDefaultTable/ColorTempGains.h
Usage: colour_temp_gains.py [--check]   (--check: fail if the header is stale). Logs to tmp/logs/colour_temp_gains.log.
Maths: daylight-locus xy (CIE 15:2004 / Judd-MacAdam-Wyszecki), sRGB matrix (IEC 61966-2-1), gain = linear ratio ^ (1/gamma)."""
import os
import subprocess
import sys

UNITY = 0x800          # 12-bit gain, 1.0 = 0x800 (usColorTempX x contrast / 2048)
GAIN_MAX = 0xFFF
GAMMA = 2.2            # contrast multiplies encoded values, panel decodes ~2.2
# Reference white = D65 (sRGB panel native assumption). 5800 K menu label = real 5800 K.
PRESETS = [("9300", 9300.0), ("7500", 7500.0), ("6500", 6500.0), ("5800", 5800.0), ("SRGB", None)]
# IEC 61966-2-1 XYZ(D65) -> linear sRGB
M = [[3.2406, -1.5372, -0.4986], [-0.9689, 1.8758, 0.0415], [0.0557, -0.2040, 1.0570]]


def repo():
    r = os.environ.get("AWTO_DDC_REPO")
    if r: return r
    try: return subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
    except (subprocess.CalledProcessError, OSError): return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def daylight_xy(t):
    # CIE daylight locus, valid 4000..25000 K
    if t <= 7000: x = 0.244063 + 0.09911e3 / t + 2.9678e6 / t**2 - 4.6070e9 / t**3
    else: x = 0.237040 + 0.24748e3 / t + 1.9018e6 / t**2 - 2.0064e9 / t**3
    return x, -3 * x * x + 2.87 * x - 0.275


def linear_rgb(x, y):
    X, Y, Z = x / y, 1.0, (1 - x - y) / y
    return [M[i][0] * X + M[i][1] * Y + M[i][2] * Z for i in range(3)]


def gains(t):
    ref = linear_rgb(0.3127, 0.3290)                       # D65
    tgt = linear_rgb(*daylight_xy(t)) if t else ref
    rel = [tgt[i] / ref[i] for i in range(3)]
    rel = [r / max(rel) for r in rel]                      # max channel stays unity: no brightness gain above contrast
    return [min(GAIN_MAX, round(UNITY * r ** (1 / GAMMA))) for r in rel]


def render():
    o = ["// Generated by scripts/colour_temp_gains.py - do not edit.",
         "#define _CT_GAIN_UNITY                              0x800"]
    for name, t in PRESETS:
        for ch, g in zip(("RED", "GREEN", "BLUE"), gains(t)):
            o.append("#define " + f"_CT{name}_{ch}".ljust(44) + f"({g})")
    return "\n".join(o) + "\n"


def main():
    R = repo()
    path = os.path.join(R, "fw/sdk/Panel/RTDColorDefaultTable/ColorTempGains.h")
    logp = os.path.join(R, "tmp/logs/colour_temp_gains.log")
    os.makedirs(os.path.dirname(logp), exist_ok=True)
    txt = render()
    lines = [f"{name} {t} R,G,B = {gains(t)}\n" for name, t in PRESETS]
    with open(logp, "w") as log:
        log.writelines(lines)
        log.write(txt)
    print(txt)
    if "--check" in sys.argv:
        with open(path) as f:
            sys.exit(0 if f.read() == txt else 1)
    with open(path, "w") as f:
        f.write(txt)


main()
