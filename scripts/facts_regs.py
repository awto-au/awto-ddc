#!/usr/bin/env python3
"""Generate the clean tree's facts/ headers from the regdb: register FACTS only (awto-ddc#65, docs/cleanroom.md).

usage: facts_regs.py [--chip RTD2795T-CG] [--out /mnt/2tb/git/awto-rtdfw/facts] [--names specs/names.tsv] [--check]
  Emits facts/regs/p<PP>.h per page, facts/regs.h (includes all pages), facts/names.h (our names, from --names).
  Kept: page, address, port index, bit range, reset, access, wide-value bit range. Dropped: every vendor register/field
  name and all description text. Positional names only:
    P31_A0 (address)  P31_A0_RST  P31_A0_B7 (1-bit mask)  P31_A0_B6_4 (+ _SH shift)
    indexed port: P00_25_I1A (index value) + _RST / _B<h>[_<l>]; several bytes at one index: _N0.._N<k> in regdb order.
  Fields named Reserved* are not emitted (vendor name used as a filter only).
  --names: our_name<TAB>target<TAB>note. target = a positional name above. Refuses an our_name equal to any vendor
           register/field name (case-insensitive) or a target that does not exist.
  --check: generate to a temp dir and diff against --out (exit 1 on drift).
Log: ./tmp/logs/facts_regs.log
"""
from __future__ import annotations

import argparse, csv, filecmp, gzip, hashlib, os, re, shutil, subprocess, sys, time
from collections import OrderedDict
from pathlib import Path


def repo_root() -> Path:
    env = os.environ.get("AWTO_DDC_REPO")
    if env:
        return Path(env)
    try:
        return Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], cwd=Path(__file__).parent,
                                            text=True, stderr=subprocess.DEVNULL).strip())
    except (subprocess.CalledProcessError, FileNotFoundError):
        return Path(__file__).resolve().parent.parent


ROOT = repo_root()
CLEAN = Path(os.environ.get("AWTO_RTDFW_REPO", "/mnt/2tb/git/awto-rtdfw"))
LOGF = None
HDR = "/* GENERATED by awto-ddc scripts/facts_regs.py from {src} (sha256 {sha}). Do not edit.\n" \
      " * Register facts only: page, address, index, bits, reset, access. Provenance: derived (vendor register database). */\n"


def log(s: str) -> None:
    line = f"{time.strftime('%Y-%m-%dT%H:%M:%S%z')} {s}"
    print(line)
    if LOGF:
        LOGF.write(line + "\n"); LOGF.flush()


def load(chip: str) -> tuple[list[dict], Path]:
    p = ROOT / "re" / "regdb" / f"{chip}.tsv.gz"
    with gzip.open(p, "rt", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t")), p


def idx_width(rows) -> dict:
    """data-port address -> hex digits of its widest index (2, 4 or 6)."""
    w = {}
    for r in rows:
        if r["port_idx"]:
            n = int(r["port_idx"])
            w[r["address"]] = max(w.get(r["address"], 2), 2 if n < 0x100 else 4 if n < 0x10000 else 6)
    return w


def build(rows) -> "OrderedDict[str, dict]":
    """-> page -> ordered {base positional name: reg dict}. Vendor names are used only to split bytes at one index."""
    widths = idx_width(rows)
    regs: OrderedDict = OrderedDict()
    seen = set()
    for r in rows:
        if not r["address"].startswith("0x"):
            continue
        key = (r["page"], r["address"], r["port_idx"], r["kind"], r["register"], r["bit_high"], r["bit_low"], r["field"])
        if key in seen:
            continue                                         # identical duplicate rows in the regdb
        seen.add(key)
        a = int(r["address"], 16)
        page = f"{a >> 8:02X}"
        base = f"P{page}_{a & 0xFF:02X}"
        if r["port_idx"]:
            base += f"_I{int(r['port_idx']):0{widths[r['address']]}X}"
        slot = regs.setdefault(page, OrderedDict()).setdefault(base, {"addr": a, "idx": r["port_idx"], "type": r["reg_type"],
                                                                      "bytes": OrderedDict()})
        b = slot["bytes"].setdefault(r["register"], {"rst": None, "acc": [], "fields": []})
        if r["kind"] == "REG":
            b["rst"] = r["reset"]
        elif r["kind"] == "FIELD":
            if r["access"] and r["access"] not in b["acc"]:
                b["acc"].append(r["access"])
            if re.match(r"reserved", r["field"], re.I):
                continue
            wide = f"{r['wide_hi']}:{r['wide_lo']}" if r["wide_lo"] and r["wide_hi"] else ""
            b["fields"].append((int(r["bit_high"]), int(r["bit_low"]), r["access"], wide))
    return regs


def emit_page(page: str, regs: dict) -> list[str]:
    L = []
    for base, s in regs.items():
        multi = len(s["bytes"]) > 1
        for n, (_, b) in enumerate(s["bytes"].items()):
            nm = f"{base}_N{n}" if multi else base
            acc = "/".join(b["acc"]) or "-"
            if s["idx"]:
                val = f"0x{int(s['idx']):X}u"
                L.append(f"#define {nm:<28} {val:<10} /* index on data port 0x{s['addr']:04X}, type {s['type']}, {acc} */")
            else:
                L.append(f"#define {nm:<28} 0x{s['addr']:04X}u    /* {acc} */")
            if b["rst"] and re.fullmatch(r"0x[0-9A-Fa-f]{1,2}", b["rst"]):
                L.append(f"#define {nm + '_RST':<28} 0x{int(b['rst'], 16):02X}u")
            fields = sorted(set(b["fields"]), key=lambda f: -f[0])
            if len(fields) == 1 and fields[0][:2] == (7, 0) and not fields[0][3]:
                continue                                     # whole-byte field: the register name says it all
            for h, lo, facc, wide in fields:
                mask = ((1 << (h - lo + 1)) - 1) << lo
                fn = f"{nm}_B{h}" if h == lo else f"{nm}_B{h}_{lo}"
                note = facc + (f"; value bits [{wide}]" if wide else "")
                L.append(f"#define {fn:<28} 0x{mask:02X}u      /* {note} */")
                if h != lo:
                    L.append(f"#define {fn + '_SH':<28} {lo}")
    return L


def vendor_names(rows) -> set:
    return {x.upper() for r in rows for x in (r["register"], r["field"]) if x}


def emit_names(names_tsv: Path, positional: set, vnames: set) -> list[str]:
    L, bad = [], []
    for n, line in enumerate(names_tsv.read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        ours, target, note = (line.split("\t") + ["", ""])[:3]
        if ours.upper() in vnames:
            bad.append(f"{names_tsv.name}:{n}: {ours} equals a vendor register/field name")
        elif target not in positional:
            bad.append(f"{names_tsv.name}:{n}: target {target} not in facts")
        elif not re.fullmatch(r"[A-Z][A-Z0-9_]*", ours):
            bad.append(f"{names_tsv.name}:{n}: {ours}: names are UPPER_SNAKE")
        L.append(f"#define {ours:<28} {target:<16}" + (f" /* {note} */" if note else ""))
    if bad:
        sys.exit("names.tsv refused:\n  " + "\n  ".join(bad))
    return L


def generate(chip: str, out: Path, names: Path | None) -> int:
    rows, src = load(chip)
    sha = hashlib.sha256(src.read_bytes()).hexdigest()[:16]
    pages = build(rows)
    if out.exists():
        shutil.rmtree(out)
    (out / "regs").mkdir(parents=True)
    hdr = HDR.format(src=f"re/regdb/{src.name}", sha=sha)
    positional, total = set(), 0
    for page, regs in pages.items():
        body = emit_page(page, regs)
        positional |= {ln.split()[1] for ln in body}
        total += len(body)
        g = f"AWTO_FACTS_P{page}_H"
        (out / "regs" / f"p{page.lower()}.h").write_text(hdr + f"#ifndef {g}\n#define {g}\n\n" + "\n".join(body) + "\n\n#endif\n")
    inc = "\n".join(f'#include "regs/p{p.lower()}.h"' for p in pages)
    (out / "regs.h").write_text(hdr + "#ifndef AWTO_FACTS_REGS_H\n#define AWTO_FACTS_REGS_H\n\n" + inc + "\n\n#endif\n")
    if names and names.exists():
        nl = emit_names(names, positional, vendor_names(rows))
        (out / "names.h").write_text(hdr.replace("Register facts only", "Our names for register facts (specs/names.tsv)")
                                     + '#ifndef AWTO_FACTS_NAMES_H\n#define AWTO_FACTS_NAMES_H\n\n#include "regs.h"\n\n'
                                     + "\n".join(nl) + "\n\n#endif\n")
        log(f"names.h: {len(nl)} names from {names}")
    log(f"{chip}: {len(pages)} pages, {sum(len(r) for r in pages.values())} registers, {total} defines -> {out}")
    return 0


def main() -> int:
    global LOGF
    ap = argparse.ArgumentParser()
    ap.add_argument("--chip", default="RTD2795T-CG")
    ap.add_argument("--out", type=Path, default=CLEAN / "facts")
    ap.add_argument("--names", type=Path, default=ROOT / "specs" / "names.tsv")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    (ROOT / "tmp/logs").mkdir(parents=True, exist_ok=True)
    LOGF = (ROOT / "tmp/logs/facts_regs.log").open("a")
    if not a.check:
        return generate(a.chip, a.out, a.names)
    tmp = ROOT / "tmp" / "facts_check"
    generate(a.chip, tmp, a.names)
    cmp = filecmp.dircmp(tmp, a.out)
    drift = cmp.diff_files + cmp.left_only + cmp.right_only + [f"regs/{x}" for x in
                                                                 (cmp.subdirs["regs"].diff_files if "regs" in cmp.subdirs else [])]
    log(f"check: {'drift ' + str(drift) if drift else 'up to date'}")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
