#!/usr/bin/env python3
"""Generate fw/simtests/crt_ops/vec.h: expected 16/32-bit mul, unsigned/signed div and mod (awto-sdcc#7 / awto-ddc#11).

usage: scripts/crt_ops_vec.py      (writes the header; C semantics: truncating division, remainder takes the dividend's sign)
Edge values x edge values + LCG(12345) pairs; divisor 0 and INT_MIN / -1 are left out (undefined / library-specific).
Log: ./tmp/logs/crt_ops_vec.log (zero divisors are tested separately in main.c)
"""
import sys
from pathlib import Path

import os
ROOT = Path(os.environ.get("AWTO_DDC_REPO") or Path(__file__).resolve().parent.parent)
E16 = [0, 1, 2, 3, 0x7F, 0x80, 0xFF, 0x100, 0x1234, 0x7FFF, 0x8000, 0x8001, 0xC000, 0xABCD, 0xFFFE, 0xFFFF]
E32 = [0, 1, 2, 3, 0x80, 0xFF, 0x100, 0xFFFF, 0x10000, 0x1FFFF, 0x12345678, 0x7FFFFFFF, 0x80000000, 0x80000001,
       0xC0000000, 0xDEADBEEF, 0xFFFFFFFE, 0xFFFFFFFF]


def sgn(v, bits):
    return v - (1 << bits) if v >> (bits - 1) else v


def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def row(a, b, bits):
    m = (1 << bits) - 1
    sa, sb = sgn(a, bits), sgn(b, bits)
    out = [a, b, (a * b) & m, a // b, a % b]
    q = tdiv(sa, sb)
    out += [q & m, (sa - q * sb) & m]
    return out


def table(name, ctype, bits, edges, nlcg, seed):
    pairs = [(a, b) for a in edges for b in edges if b]
    x = seed
    m = (1 << bits) - 1
    for _ in range(nlcg):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        a = (x ^ (x << 7)) & m
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        b = ((x >> 3) & m) >> ((x >> 20) % bits)   # varied divisor magnitudes
        if b:
            pairs.append((a, b))
    w = 8 if bits == 32 else 4
    lines = [f"static const struct {{ {ctype} a, b, mul, divu, modu, divs, mods; }} {name}[] = {{"]
    for a, b in pairs:
        if sgn(a, bits) == -(1 << (bits - 1)) and sgn(b, bits) == -1:
            continue
        lines.append("    {" + ", ".join(f"0x{v:0{w}X}U" + ("L" if bits == 32 else "") for v in row(a, b, bits)) + "},")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = ["/* generated by scripts/crt_ops_vec.py (awto-sdcc#7 / awto-ddc#11): a, b, a*b, a/b, a%b (unsigned), a/b, a%b (signed bits) */",
           table("V16", "unsigned int", 16, E16, 60, 12345), table("V32", "unsigned long", 32, E32, 60, 54321), ""]
    (ROOT / "fw/simtests/crt_ops/vec.h").write_text("\n".join(out))
    (ROOT / "tmp/logs").mkdir(parents=True, exist_ok=True)
    (ROOT / "tmp/logs/crt_ops_vec.log").open("a").write("wrote fw/simtests/crt_ops/vec.h\n")
    print("wrote fw/simtests/crt_ops/vec.h")


if __name__ == "__main__":
    sys.exit(main())
