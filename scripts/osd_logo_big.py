#!/usr/bin/env python3
"""Big boot-logo generator: awto mark drawn from its SVG geometry at full cell resolution, tiled with shared solid tiles (#63).

usage: osd_logo_big.py [--rows 58] [--cols 95] [--selftest] [--preview OUT.png] [--write]
  Geometry = docs/logo/awto-monitor-mark.svg (256-unit box): outline rect, circle breaking its top edge, neck + foot.
  Cell grid rows x cols of 12x18 px tiles; art scaled to fill the grid height. Polarity as osd_logo_encode: 1 = black box, 0 = artwork.
  Out (--write): fw/sdcc/awto_logo_icons.inc (tICON_REALTEK_1BIT_LOGO0/1 blobs, tiles 0..79 / 80..) and
  fw/sdcc/awto_logo_maps.inc (run-length map tAWTO_LOGO_RUNS + AwtoLogoDraw()).
Log: tmp/logs/osd_logo_big.log
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np  # noqa: E402
from PIL import Image, ImageDraw  # noqa: E402
import osd_logo_encode as E  # noqa: E402

TW, TH, TB = E.TW, E.TH, E.TB
SPLIT = 80                      # LOGO0 loads at font id 0, LOGO1 at _Logo1_0x00 = 80


def art(W: int, H: int, ss: int = 4) -> np.ndarray:
    """1 = ink (stroke) for the mark, art box scaled to fit W x H px (centred), supersampled then thresholded."""
    x0, y0, x1, y1 = 32.5, 46.5, 223.5, 221.5               # stroke bbox in the 256-unit SVG
    s = min((W - 4) / (x1 - x0), (H - 4) / (y1 - y0))
    ox, oy = (W - (x1 - x0) * s) / 2 - x0 * s, (H - (y1 - y0) * s) / 2 - y0 * s
    im = Image.new("L", (W * ss, H * ss), 0)
    d = ImageDraw.Draw(im)

    def P(x, y):
        return ((ox + x * s) * ss, (oy + y * s) * ss)

    def box(a, b, c, e, fill):
        d.rectangle([*P(a, b), *P(c, e)], fill=fill)

    def circ(cx, cy, r, fill):
        d.ellipse([*P(cx - r, cy - r), *P(cx + r, cy + r)], fill=fill)
    box(32.5, 68.5, 223.5, 195.5, 255)                       # screen outline = rect stroke 7 around 36,72..220,192
    box(39.5, 75.5, 216.5, 188.5, 0)
    circ(128, 72, 25.5, 255)                                 # circle ring (its inside hides the top edge)
    circ(128, 72, 18.5, 0)
    box(124.5, 195.5, 131.5, 221.5, 255)                     # neck
    box(86.5, 214.5, 169.5, 221.5, 255)                      # foot
    return (np.asarray(im.resize((W, H), Image.BOX)) >= 128).astype(np.uint8)


def build(rows: int, cols: int):
    ink = art(cols * TW, rows * TH)
    box = 1 - ink                                            # 1 = black box
    uniq, ids, grid = [], {}, []
    solid = b"\xff" * TB
    uniq.append(solid); ids[solid] = 0                       # id 0 = solid box tile (also the pad)
    for r in range(rows):
        row = []
        for c in range(cols):
            tb = E.tile_bytes(box[r * TH:(r + 1) * TH, c * TW:(c + 1) * TW])
            if tb not in ids:
                ids[tb] = len(uniq); uniq.append(tb)
            row.append(ids[tb])
        grid.append(row)
    return box, uniq, grid


def runs(grid):
    out = bytearray()
    for row in grid:
        i = 0
        while i < len(row):
            j = i
            while j < len(row) and row[j] == row[i] and j - i < 255:
                j += 1
            out += bytes([j - i, row[i]])
            i = j
    return bytes(out)


def unrun(data: bytes, cols: int):
    rows, row, p = [], [], 0
    while p < len(data):
        row += [data[p + 1]] * data[p]
        p += 2
        if len(row) == cols:
            rows.append(row); row = []
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=58)
    ap.add_argument("--cols", type=int, default=95)
    ap.add_argument("--preview")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    box, uniq, grid = build(a.rows, a.cols)
    if len(uniq) > 256:
        sys.exit(f"{len(uniq)} unique tiles > 256: ids need B0 bit5 (not supported by the 8-bit run map)")
    t0, t1 = b"".join(uniq[:SPLIT]), b"".join(uniq[SPLIT:]) or b"\xff" * TB
    b0, b1 = E.encode_blob(t0, E.freq_map(t0)), E.encode_blob(t1, E.freq_map(t1))
    rl = runs(grid)
    assert unrun(rl, a.cols) == grid
    cells = a.rows * a.cols
    E.log(f"{a.cols}x{a.rows} cells = {a.cols * TW}x{a.rows * TH} px (1x), {cells} cells, {len(uniq)} unique tiles; "
          f"SRAM words {a.rows + 1 + cells + 9 * len(uniq)} of 12288; blobs {len(b0)} + {len(b1)} B (slots 1258 + 1126); run map {len(rl)} B")
    if a.preview:
        Image.fromarray((255 - box * 255).astype("uint8")).save(a.preview)
    if a.write:
        hdr = "// GENERATED by scripts/osd_logo_big.py from docs/logo/awto-monitor-mark.svg geometry (awto-ddc#63). Do not edit.\n"
        (E.ROOT / "fw/sdcc/awto_logo_icons.inc").write_text(hdr + E.c_array("tICON_REALTEK_1BIT_LOGO0", b0, comment=f"tiles 0..{min(len(uniq), SPLIT) - 1}") +
                                                         E.c_array("tICON_REALTEK_1BIT_LOGO1", b1, comment=f"tiles {SPLIT}.."))
        draw = (
            "// run-length char map -> font select SRAM: one address set + n writes per run (OsdFontPut1Bit: 0x4C = 1-bit, 12 px)\n"
            "void AwtoLogoDraw(void)\n{\n    BYTE r, c, n, id;\n    WORD i = 0;\n\n"
            "    for(r = 0; r < AWTO_LOGO_ROWS; r++)\n    {\n        for(c = 0; c < AWTO_LOGO_COLS; c += n)\n        {\n"
            "            n = tAWTO_LOGO_RUNS[i++];\n            id = tAWTO_LOGO_RUNS[i++];\n"
            "            ScalerOsdCharCommandAllByteSeries(g_usFontSelectStart + (WORD)r * AWTO_LOGO_COLS + c, 0x4C, id, COLOR(_LOGO_CP_BG, _LOGO_CP_BG), n);\n"
            "        }\n    }\n}\n")
        body = E.c_array("tAWTO_LOGO_RUNS", rl, per=16, comment=f"{a.cols}x{a.rows} cells, rows of [count, tile id] runs")
        (E.ROOT / "fw/sdcc/awto_logo_maps.inc").write_text(hdr + body + draw)
        (E.ROOT / "fw/sdcc/awto_logo_big.inc").unlink(missing_ok=True)
        E.log("wrote fw/sdcc/awto_logo_icons.inc, awto_logo_maps.inc; Project.h needs AWTO_LOGO_COLS %d / AWTO_LOGO_ROWS %d" % (a.cols, a.rows) + "")
    return 0


if __name__ == "__main__":
    sys.exit(main())
