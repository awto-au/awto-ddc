#!/usr/bin/env python3
"""Generate fw/test/pacman_full_data.inc: the full-screen Pac-Man demo (archived image pacland14, 2026-11-09) for our firmware (awto-ddc#227 side project).

usage: gen_pacman_full.py [--image BIN --map MAP] [--steps N] [--check]
  Reads the glyph stream (85 glyphs x 108 B = 24x36, 36 SRAM words each), the 80 x 60 cell map, the per-glyph colour, the actor phase table
  and the palette out of the image through scripts/pacman_emulator.py (load_assets), runs its autonomous demo for N steps and records every
  step as cell updates (cell index u16 LE, glyph, colour = 4 bytes). Initial cells carry the glyph only (colour from the per-glyph table, actor cells fixed up); updates carry glyph + colour; the firmware builds the
  OSD char command (B0 = 0x58 | glyph bit 8, B1 = glyph, B2 = colour << 4 | background 1).
  Default image: build-debris/images/AWT26110002-pacland14-be.{bin,map} (gitignored; the include is committed). --check: exit 1 if stale.
Log: ./tmp/logs/gen_pacman_full.log
"""
import argparse
import os
import sys
import isostamp  # noqa: E402
from pathlib import Path

ROOT = Path(os.environ.get("AWTO_DDC_REPO") or Path(__file__).resolve().parent.parent)
sys.path.insert(0, str(Path(__file__).resolve().parent))
import pacman_emulator as P  # noqa: E402

OUT = ROOT / "fw/test/pacman_full_data.inc"
LOG = ROOT / "tmp/logs/gen_pacman_full.log"
IMG = ROOT / "build-debris/images/AWT26110002-pacland14-be"
COLS, ROWS = 80, 60
BANK = 12                                  # glyphs + palette + the entry function + (below) the second half of the steps
BANK_STEPS_B = 11                          # step tables + their readers (24 KB; bank 13 has only ~6 KB free)
BANK_STEPS = 12                            # maze, steps and their writers (~30 KB: bank 12 has ~36 KB free)
STEPS = 200                                # 25 s at 8 fps, then the maze is redrawn from the start (the 45 KB bank holds ~200 steps)


def say(s: str) -> None:
    LOG.parent.mkdir(parents=True, exist_ok=True)
    line = f"{isostamp.now()} {s}"
    with LOG.open("a") as f:
        f.write(line + "\n")
    print(line, flush=True)


def cells(demo: "P.Demo", a: "P.Assets"):
    """(glyph, colour) per cell as pacman_emulator.render composes them."""
    actors = {}

    def actor(slot, frame_id, colour):
        off = frame_id * 4
        for part, gid in enumerate(a.phase[off:off + 4]):
            if gid:
                actors[(demo.x[slot] + (part & 1), demo.y[slot] + (part >> 1))] = (gid, colour)
    actor(0, demo.direction[0] * 2 + demo.mouth, 3)
    for i in range(1, 5):
        actor(i, 8, 4 + i)
    out = []
    for y in range(ROWS):
        for x in range(COLS):
            logical = a.grid[y * COLS + x]
            if (x, y) in demo.eaten and logical in (1, 2):
                logical = 0
            out.append(actors.get((x, y), (logical, a.fg[logical] if logical < len(a.fg) else 0)))
    return out


def arr(name: str, data: bytes, per: int, bank: int) -> str:
    rows = ["    " + ", ".join(f"0x{b:02X}" for b in data[i:i + per]) + "," for i in range(0, len(data), per)]
    return f"#pragma place bank({bank})\nstatic const uint8_t __code {name}[{len(data)}] = {{\n" + "\n".join(rows) + "\n};\n"


def build(image: Path, mp: Path, steps: int) -> str:
    a = P.load_assets(image, mp, COLS * ROWS)
    assert a.logical_bytes == 108 and len(a.slots) == len(a.fg)
    raw = P.chunk(image.read_bytes(), mp.read_text(errors="replace"), "pm_glyph_bytes")
    demo = P.Demo(a, COLS, ROWS)
    cur = cells(demo, a)
    init = bytes(g for g, _ in cur)                                        # glyph per cell; colour = fg[glyph] except the fix-ups (actor cells)
    fix = bytearray()
    for pos, (g, c) in enumerate(cur):
        if c != a.fg[g]:
            fix += bytes([pos & 0xFF, pos >> 8, c])
    halves = [[], []]                                                          # steps 0..N/2-1 and N/2..N-1: two tables (bank holes are < 24 KB)
    for h in (0, 1):
        idx, stream = [], bytearray()
        lo, hi = (0, steps // 2) if h == 0 else (steps // 2, steps)
        for _ in range(lo, hi):
            demo.step()
            nxt = cells(demo, a)
            idx.append(len(stream))
            for pos, (n, o) in enumerate(zip(nxt, cur)):
                if n != o:
                    stream += bytes([pos & 0xFF, pos >> 8, n[0], n[1]])
            cur = nxt
        idx.append(len(stream))
        halves[h] = (b"".join(bytes([v & 0xFF, v >> 8]) for v in idx), bytes(stream))
    pal = b"".join(bytes(c) for c in a.palette)                          # index 0 .. 9: index 1 = opaque black (the B2 background), 0 is transparent
    head = ("/* pacman_full_data.inc: GENERATED by scripts/gen_pacman_full.py from the pacland14 image. Do not edit.\n"
            " * Read by fw/test/pacman_full.c via movc: same bank. */\n"
            f"#define AWTO_PF_COLS            {COLS}\n#define AWTO_PF_ROWS            {ROWS}\n#define AWTO_PF_GLYPHS          {len(a.slots)}\n"
            f"#define AWTO_PF_STEPS           {steps}\n#define AWTO_PF_HALF            {steps // 2}\n#define AWTO_PF_PAL_N           {len(a.palette)}\n")
    return (head + arr("g_pfPal", pal, 3, BANK) + arr("g_pfGlyph0", raw[:3060], 27, BANK) + arr("g_pfGlyph1", raw[3060:6120], 27, BANK)
            + arr("g_pfGlyph2", raw[6120:], 27, BANK) + arr("g_pfCell", init, 40, BANK) + arr("g_pfFg", bytes(a.fg), 17, BANK)
            + arr("g_pfFix", bytes(fix), 15, BANK)
            + arr("g_pfIdxA", halves[0][0], 16, BANK_STEPS_B) + arr("g_pfDeltaA", halves[0][1], 16, BANK_STEPS_B)
            + arr("g_pfIdxB", halves[1][0], 16, BANK_STEPS_B) + arr("g_pfDeltaB", halves[1][1], 16, BANK_STEPS_B))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--image", type=Path, default=IMG.with_suffix(".bin"))
    ap.add_argument("--map", type=Path, default=IMG.with_suffix(".map"))
    ap.add_argument("--steps", type=int, default=STEPS)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check and not a.image.exists():
        say("image absent: --check skipped (the include is committed)")
        return 0
    text = build(a.image, a.map, a.steps)
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        say(f"{OUT} {'up to date' if ok else 'STALE'}")
        return 0 if ok else 1
    OUT.write_text(text)
    n = text.count("0x")
    say(f"wrote {OUT}: {n} data bytes, steps {a.steps}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
