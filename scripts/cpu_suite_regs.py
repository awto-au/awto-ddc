#!/usr/bin/env python3
"""Register tables of the CPU suite image (docs/cpu-suite.md): fw/test/cpu_suite_regs.inc from re/regmap/regs.tsv.

usage: cpu_suite_regs.py [--check]
  RD table  = per scaler page up to 2 registers that read one constant value in every live observation (obs_n >= 10, obs_const set),
              no side effect in the map, not in reg_live_scan.EXCLUDE, access without W1C / RC, name without port / FIFO / status words,
              not on a read-behind page (dbg_xdata.BEHIND_PAGES: a first read of a dword is stale = false garbled read), not on RAM pages D1..FC.
              The suite reads each one back-to-back at a MOVX stretch and compares with the constant: a mismatch is a garbled read.
  WR table  = per page up to 1 blank-reserved DUMMY / RESERVED register the SDK does not use (sdk_uses 0) that read 00 in every
              observation: candidate scratch registers for write-then-read-back. The firmware writes them only with the host's
              explicit write flag (default off); hardware safety of each entry is unverified (Phase B decides).
  --check: exit 1 when the file on disk differs from the regenerated one.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dbg_xdata as X
import reg_live_scan as L
from _repo import ROOT

OUT = ROOT / "fw/test/cpu_suite_regs.inc"
MIN_OBS = 10                    # observations a constant must hold over (live reads on 3 units, several states)
MIN_OBS_WR = 20
RAM_PAGES = range(0xD1, 0xFD)   # firmware XDATA RAM (docs/live-register-scan.md): constants there are image facts, not registers
MAX_PAGE = 0xFD                 # pages FE / FF are the MCU's own registers (DDC, IIC, flash controller): not in the table
RD_PER_PAGE = 2
BAD_WORDS = ("PORT", "FIFO", "STATUS", "FLAG", "RESULT", "DATA", "INT_", "IRQ", "READ", "KEY", "HDCP", "SRAM", "TABLE")
BAD_ACCESS = ("W1C", "RC")


def rows() -> list[dict]:
    with (ROOT / "re/regmap/regs.tsv").open() as f:
        return list(csv.DictReader(f, delimiter="\t"))


def safe_read(r: dict) -> bool:
    a = int(r["key"], 16)
    return (a >> 8) <= MAX_PAGE and (a >> 8) not in X.BEHIND_PAGES and (a >> 8) not in RAM_PAGES and not r["side_effects"] and not L.excluded(a) and not any(b in r["access"] for b in BAD_ACCESS) \
        and not any(w in r["regdb_name"].upper() for w in BAD_WORDS) and r["class"] != "status"


def build() -> tuple[list[tuple[int, int]], list[int]]:
    rd: dict[int, list[tuple[int, int]]] = {}
    wr: dict[int, int] = {}
    for r in rows():
        if not r["obs_n"] or not safe_read(r):
            continue
        a, n = int(r["key"], 16), int(r["obs_n"])
        if r["obs_const"] and n >= MIN_OBS:
            rd.setdefault(a >> 8, []).append((a, int(r["obs_const"], 16)))
            if (r["regdb_status"] == "blank-reserved" and n >= MIN_OBS_WR and r["obs_const"] == "00" and r["sdk_uses"] in ("", "0")
                    and ("DUMMY" in r["regdb_name"].upper() or "RESERVED" in r["regdb_name"].upper()) and not r["class"]):
                wr.setdefault(a >> 8, a)
    rd_out: list[tuple[int, int]] = []
    for pg in sorted(rd):
        lst = rd[pg]
        pick = [lst[0], lst[len(lst) // 2]][:RD_PER_PAGE] if len(lst) > 1 else lst
        rd_out += pick if pick[0] != pick[-1] else pick[:1]
    return rd_out, [wr[p] for p in sorted(wr)]


def render() -> str:
    rd, wr = build()
    s = ["/* cpu_suite_regs.inc: GENERATED by scripts/cpu_suite_regs.py from re/regmap/regs.tsv. Do not edit. Read by fw/test/cpu_suite.c. */",
         f"#define AWTO_CPU_RD_N                           {len(rd)}",
         f"#define AWTO_CPU_WR_N                           {len(wr)}",
         "static const __code WORD tAwtoCpuRdAddr[AWTO_CPU_RD_N] = {"]
    s += [", ".join(f"0x{a:04X}" for a, _ in rd[i:i + 8]) + "," for i in range(0, len(rd), 8)]
    s += ["};", "static const __code BYTE tAwtoCpuRdVal[AWTO_CPU_RD_N] = {"]
    s += [", ".join(f"0x{v:02X}" for _, v in rd[i:i + 8]) + "," for i in range(0, len(rd), 8)]
    s += ["};", "static const __code WORD tAwtoCpuWrAddr[AWTO_CPU_WR_N] = {"]
    s += [", ".join(f"0x{a:04X}" for a in wr[i:i + 8]) + "," for i in range(0, len(wr), 8)]
    s += ["};", ""]
    return "\n".join(s)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    rd, wr = build()
    print(f"{OUT}: {len(rd)} read entries over {len({a >> 8 for a, _ in rd})} pages, {len(wr)} scratch candidates")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
