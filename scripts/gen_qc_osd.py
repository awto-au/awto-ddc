#!/usr/bin/env python3
"""Generate fw/test/qc_osd_data.inc from Realtek's QC OSD source (awto-ddc#227): the font / map blobs and the palette of the QC test.

usage: gen_qc_osd.py [--qc FILE] [--out FILE] [--check]
  Reads tQCDRAW_MAP, tQCFONT_GLOBAL, tQCFONT_2BITBROOK, tQCFONT_4BITLUFFY and tPALETTE_QC from the upstream mirror
  (RL6449_Series_QC_OSD.c, Kingdomwhisky/RTD-Scaler-TEST) and writes them as C arrays, each under `#pragma place bank(12)` so
  they share a bank with the loader (fw/test/qc_osd.c reads them via movc). --check: exit 1 when the file on disk differs.
Log: ./tmp/logs/gen_qc_osd.log
"""
import argparse
import os
import re
import sys
from pathlib import Path

import isostamp

ROOT = Path(os.environ.get("AWTO_DDC_REPO") or Path(__file__).resolve().parent.parent)
LOG = ROOT / "tmp/logs/gen_qc_osd.log"
QC = Path("/mnt/2tb/git_mirror/Kingdomwhisky/RTD-Scaler-TEST/Kernel/Scaler/RL6449_Series_Scaler/Code/RL6449_Series_QC_OSD.c")
OUT = ROOT / "fw/test/qc_osd_data.inc"
TABLES = (("tQCDRAW_MAP", "g_qcMap"), ("tQCFONT_GLOBAL", "g_qcGlobal"), ("tQCFONT_2BITBROOK", "g_qcBrook"),
          ("tQCFONT_4BITLUFFY", "g_qcLuffy"), ("tPALETTE_QC", "g_qcPal"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--qc", type=Path, default=QC)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    src = a.qc.read_text(errors="replace")
    out = ["/* qc_osd_data.inc: GENERATED by scripts/gen_qc_osd.py from Realtek's RL6449_Series_QC_OSD.c (QC test font, map and palette data).",
           " * Do not edit. Read by fw/test/qc_osd.c via movc: same bank (awto-ddc#149 / #227). */"]
    for src_name, c_name in TABLES:
        m = re.search(rf"BYTE code {src_name}\[\]\s*=\s*\{{(.*?)\}};", src, re.DOTALL)
        if not m:
            sys.exit(f"{src_name} not in {a.qc}")
        b = bytes(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(1)))
        out.append(f"#pragma place bank(12)\nstatic const uint8_t __code {c_name}[{len(b)}] = {{")
        for i in range(0, len(b), 16):
            out.append("    " + ", ".join(f"0x{x:02x}" for x in b[i:i + 16]) + ",")
        out.append("};")
    text = "\n".join(out) + "\n"
    LOG.parent.mkdir(parents=True, exist_ok=True)
    if a.check:
        ok = a.out.exists() and a.out.read_text() == text
        print("up to date" if ok else "OUT OF DATE")
        return 0 if ok else 1
    a.out.write_text(text)
    with LOG.open("a") as f:
        f.write(f"{isostamp.now()} wrote {a.out} ({len(text)} chars)\n")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
