BOX = [0x1F] * 7                                   # fallback for an unknown char


def cell_rows(ch: str):
    """Return 18 cell rows (12-bit ints, bit11 = leftmost) for `ch`.
    5x7 scaled x2 -> 10x14, centred in the 12x18 cell with a 1px left margin."""
    g = F.get(ch.upper() if ch.upper() in F else ch, None)
    if g is None:
        g = F.get(ch, BOX)
    rows = [0] * CELL_H
    for r in range(7):
        bits = 0
        for c in range(5):
            if (g[r] >> (4 - c)) & 1:
                bits |= 0b11 << (2 * (4 - c))       # double each column -> 10 px wide
        line = bits << 1                            # 1px left margin inside 12-bit row
        rows[2 + 2 * r] = line                      # vertical x2: rows 2..15
        rows[3 + 2 * r] = line
    return rows


def glyph_words(ch: str):
    """9 OSD words (b0,b1,b2 each, Byte0=LSB) for `ch`. pack 0 layout (matches rtd_osd/make_logo)."""
    rows = cell_rows(ch)
    out = []
    for k in range(WORDS_PER_GLYPH):
        a, b = rows[2 * k], rows[2 * k + 1]
        w = (a << 12) | b
        out.append((w & 0xFF, (w >> 8) & 0xFF, (w >> 16) & 0xFF))
    return out


def charset(text: str) -> str:
    """Unique chars in `text` (space first so blank = glyph 0), as an upload order."""
    seen = {" ": None}
    for c in text:
        seen[c] = None
    return "".join(seen)
