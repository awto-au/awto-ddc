#!/usr/bin/env python3
"""awto mark -> 6x4-tile 1-bit main-menu icon (VLC, same codec as the logo) for the pop-up left slot (#46).

usage: osd_icon_encode.py selftest    round-trip SDK tFONT1_ICON_INFORMATION byte-identical
       osd_icon_encode.py generate    write fw/sdcc/awto_icon_info.inc + tmp/logs/awto_icon_preview.png
Format = osd_logo_encode.py (blob/tile). Icon: 24 tiles in row-major 6x4 order, 1 = foreground (drawn _CP_WHITE), 0 = window colour.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402
import osd_logo_encode as L  # noqa: E402
from glyph_decode import decode_blob  # noqa: E402

W, H = 6 * L.TW, 4 * L.TH          # 72 x 72 px
SDK_SRC = L.OSD / "RTD2014OsdFontDynamicIcon_1.c"
SLOT = 388                          # layout slot of _tFONT1_ICON_INFORMATION (fw/bank_layout.tsv)


def sdk_icon(name="INFORMATION"):
    m = re.search(r"tFONT1_ICON_%s\[\]=\s*\{(.*?)\n\};" % name, SDK_SRC.read_text(), re.S)
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1)))


def selftest():
    blob = sdk_icon()
    _, n, by = decode_blob(blob, 0)
    enc = L.encode_blob(by, L.decode_map_header(blob))
    ok = enc == blob and len(blob) == 10 + n
    L.log(f"icon selftest INFORMATION: tiles={len(by) // L.TB} N={n} sizeof={len(blob)} vlc-roundtrip={enc == blob}")
    return 0 if ok else 1


def render(margin=3):
    a = np.asarray(Image.open(L.MARK_PNG).convert("RGB")).astype(int)
    white = a.min(axis=2) > 160
    ys, xs = np.where(white)
    crop = Image.fromarray((white[ys.min():ys.max() + 1, xs.min():xs.max() + 1] * 255).astype("uint8"))
    s = min((H - 2 * margin) / crop.height, (W - 2 * margin) / crop.width)
    sz = (max(1, round(crop.width * s)), max(1, round(crop.height * s)))
    crop = crop.resize(sz, Image.LANCZOS)
    cv = Image.new("L", (W, H), 0)
    cv.paste(crop, ((W - sz[0]) // 2, (H - sz[1]) // 2))
    return (np.asarray(cv) >= 110).astype(np.uint8)       # 1 = ink


def generate():
    g = render()
    by = b"".join(L.tile_bytes(g[r * L.TH:(r + 1) * L.TH, c * L.TW:(c + 1) * L.TW]) for r in range(4) for c in range(6))
    blob = L.encode_blob(by, L.freq_map(by))
    assert decode_blob(blob, 0)[2] == by
    L.log(f"awto icon: 24 tiles, blob {len(blob)} B (slot {SLOT} B) {'OK fits' if len(blob) <= SLOT else 'TOO BIG'}")
    if len(blob) > SLOT:
        sys.exit("icon larger than slot")
    hdr = "// GENERATED by scripts/osd_icon_encode.py from docs/logo/awto-monitor-mark.png (awto-ddc#46). Do not edit.\n"
    (L.ROOT / "fw/sdcc/awto_icon_info.inc").write_text(hdr + L.c_array("tFONT1_ICON_INFORMATION", blob, comment="awto mark, 6x4 tiles, replaces the SDK info bubble"))
    png = L.ROOT / "tmp/logs/awto_icon_preview.png"
    bg, fg = np.array([0, 60, 170]), np.array([255, 255, 255])    # preview colours only (blue window, white ink)
    img = np.where(g[..., None] == 1, fg, bg).astype("uint8")
    Image.fromarray(img).resize((W * 4, H * 4), Image.NEAREST).save(png)
    L.log(f"preview {png}")
    return 0


if __name__ == "__main__":
    c = sys.argv[1] if len(sys.argv) > 1 else ""
    sys.exit(selftest() if c == "selftest" else generate() if c == "generate" else (print(__doc__) or 2))
