#!/usr/bin/env python3
"""Our OSD font: ASCII 0x20..0x7E as 12x18 1-bit cells, rasterised from DejaVu Sans Mono Bold (Bitstream Vera
licence: free use, modified bitmaps allowed). Writes awto/settings/font_tab.inc (format: awto/include/osd.h).

usage: tools/gen_font.py [--ttf PATH] [--size PX] [--png tmp/font.png]
Log: ./tmp/logs/gen_font.log
"""
import argparse
import os
import time
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(os.environ.get("AWTO_RTDFW_REPO") or Path(__file__).resolve().parents[1])
TTF = "/usr/share/fonts/dejavu-sans-mono-fonts/DejaVuSansMono-Bold.ttf"
W, H = 12, 18
BASELINE = 14            # pixel row of the baseline: room for descenders (g, p, y) below, caps above


def glyph(font, ch):
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    x0, _, x1, _ = d.textbbox((0, 0), ch, font=font, anchor="ls")
    d.text(((W - (x1 - x0)) // 2 - x0, BASELINE), ch, font=font, fill=255, anchor="ls")
    return [[1 if im.getpixel((x, y)) >= 110 else 0 for x in range(W)] for y in range(H)]


def pack(px):
    """9 words x (B0, B1, B2): word w = rows 2w (bits 23..12) and 2w+1 (bits 11..0), MSB = left pixel"""
    out = []
    for w in range(9):
        v = 0
        for x in range(W):
            v |= px[2 * w][x] << (23 - x)
            v |= px[2 * w + 1][x] << (11 - x)
        out += [v & 0xFF, v >> 8 & 0xFF, v >> 16 & 0xFF]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", default=TTF)
    ap.add_argument("--size", type=int, default=16)
    ap.add_argument("--png", type=Path)
    a = ap.parse_args()
    font = ImageFont.truetype(a.ttf, a.size)
    chars = [chr(c) for c in range(0x20, 0x7F)]
    gl = [glyph(font, ch) for ch in chars]
    lines = ["/* font_tab.inc: GENERATED by tools/gen_font.py (DejaVu Sans Mono Bold %d px, Bitstream Vera licence)."
             % a.size, " * ASCII 0x20..0x7E, 27 bytes per 12x18 cell (osd.h glyph format). Do not edit. */",
             "static const uint8_t __code font_tab[OSD_FONT_N * 27] = {"]
    for ch, px in zip(chars, gl):
        b = pack(px)
        lines.append("    " + ", ".join(f"0x{x:02X}" for x in b) + f",  /* {ch!r} */".replace("*/'", "*/ '"))
    lines.append("};\n")
    (ROOT / "awto/settings/font_tab.inc").write_text("\n".join(lines))
    if a.png:
        cols = 19
        im = Image.new("L", (cols * (W + 2), ((len(gl) + cols - 1) // cols) * (H + 2)), 128)
        for i, px in enumerate(gl):
            for y in range(H):
                for x in range(W):
                    im.putpixel(((i % cols) * (W + 2) + x, (i // cols) * (H + 2) + y), 255 if px[y][x] else 0)
        a.png.parent.mkdir(parents=True, exist_ok=True)
        im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(a.png)
    (ROOT / "tmp/logs").mkdir(parents=True, exist_ok=True)
    with (ROOT / "tmp/logs/gen_font.log").open("a") as f:
        f.write(time.strftime("%Y-%m-%dT%H:%M:%S%z ") + f"font_tab.inc: {len(gl)} glyphs, {a.ttf} {a.size} px\n")
    print(f"font_tab.inc: {len(gl)} glyphs")


if __name__ == "__main__":
    main()
