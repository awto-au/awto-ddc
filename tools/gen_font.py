#!/usr/bin/env python3
"""The awto OSD font: fixed-pitch 24 x 36 px characters at 2 bpp (a 4 level white ramp), cut into 12 x 18 tiles (4 per character),
identical tiles shared, VLC compressed with scripts/osd_vlc.py (awto-ddc, the one shared codec). Charset = awto/osd/charset.txt.

usage: tools/gen_font.py [--ttf PATH] [--size PX] [--png OUT.png]
  Writes awto/osd/font_data.inc: font_ids[] (4 tile ids per character 0x20..0x7E), the VLC blob chunks, FONT_LOAD_CHUNKS.
  Fails if more than 256 distinct tiles are needed (the char word has an 8 bit tile id).
  Tile format (osd_vlc.pack_unit): 12 x 18 px, 2 bit per pixel, row-major, MSB first, 24-bit words stored low byte first;
  pixel level v selects colour c<v> of the char word [derived 2 bpp layout: prove on hardware before relying on it].
Needs awto-ddc scripts/ (osd_vlc.py): $AWTO_DDC_MAIN, default /mnt/2tb/git/awto-ddc. Log: ./tmp/logs/gen_font.log
"""
import argparse
import os
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(os.environ.get("AWTO_RTDFW_REPO") or Path(__file__).resolve().parents[1])
sys.path.insert(0, str(Path(os.environ.get("AWTO_DDC_MAIN", "/mnt/2tb/git/awto-ddc")) / "scripts"))
import osd_vlc  # noqa: E402

TTF = "/usr/share/fonts/dejavu-sans-mono-fonts/DejaVuSansMono.ttf"
CW, CH, TW, TH = 24, 36, 12, 18
FIRST, LAST = 0x20, 0x7E
TILE_BYTES = TW * TH * 2 // 8            # 54
LOG = ROOT / "tmp/logs/gen_font.log"


def log(s):
    LOG.parent.mkdir(parents=True, exist_ok=True)
    line = time.strftime("%Y-%m-%dT%H:%M:%S%z ") + s
    print(line)
    with LOG.open("a") as f:
        f.write(line + "\n")


def charset():
    text = (ROOT / "awto/osd/charset.txt").read_text()
    return sorted(set(c for c in text if FIRST <= ord(c) <= LAST and c != "\n"))


def raster(font, ch):
    """one character -> 36 x 24 levels 0..3 (antialiased, centred in the cell)"""
    asc, desc = font.getmetrics()
    top = max(0, (CH - (asc + desc)) // 2)
    im = Image.new("L", (CW, CH), 0)
    ImageDraw.Draw(im).text((int((CW - font.getlength(ch)) // 2), top), ch, 255, font=font)
    return np.rint(np.asarray(im, np.float32) * 3 / 255).astype(np.uint8)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", default=TTF)
    ap.add_argument("--size", type=int, default=30)
    ap.add_argument("--png", type=Path)
    a = ap.parse_args()
    font = ImageFont.truetype(a.ttf, a.size, layout_engine=ImageFont.Layout.BASIC)
    chars = charset()
    blank = bytes(TILE_BYTES)
    tiles, ids = [blank], {blank: 0}
    quads = {}
    for ch in chars:
        lv = raster(font, ch)
        q = []
        for ty in range(2):
            for tx in range(2):
                t = osd_vlc.pack_unit(lv[ty * TH:(ty + 1) * TH, tx * TW:(tx + 1) * TW], 2)
                if t not in ids:
                    ids[t] = len(tiles)
                    tiles.append(t)
                q.append(ids[t])
        quads[ch] = q
    if len(tiles) > 256:
        sys.exit(f"{len(tiles)} distinct tiles > 256 (8 bit tile id): drop characters from awto/osd/charset.txt")
    fallback = quads.get("?", [0, 0, 0, 0])
    rows = []
    for c in range(FIRST, LAST + 1):
        q = quads.get(chr(c), fallback if chr(c) != " " else [0, 0, 0, 0])
        rows.append("    " + ", ".join(str(x) for x in q) + f",  /* {chr(c)!r} */".replace("*/'", "*/ '"))
    data = b"".join(tiles)
    chunks = osd_vlc.encode_chunks(data, TILE_BYTES)
    out = ["/* font_data.inc: GENERATED by tools/gen_font.py (DejaVu Sans Mono, Bitstream Vera licence, %d px, 24 x 36 px characters, 2 bpp)." % a.size,
           " * %d characters, %d tiles of 12 x 18 (shared), %d B raw, %d B VLC in %d blob(s). Do not edit. */" % (
               len(chars), len(tiles), len(data), sum(len(b) for _, _, b in chunks), len(chunks)),
           f"#define OSD_FONT_FIRST  0x{FIRST:02X}", f"#define OSD_FONT_LAST   0x{LAST:02X}", f"#define OSD_FONT_TILES  {len(tiles)}",
           f"static const uint8_t __code font_ids[{(LAST - FIRST + 1) * 4}] = {{"] + rows + ["};", ""]
    load = []
    for i, (first, n, blob) in enumerate(chunks):
        out.append(f"/* blob {i}: tiles {first}..{first + n - 1} */")
        out.append(f"static const uint8_t __code font_blob{i}[{len(blob)}] = {{")
        for k in range(0, len(blob), 16):
            out.append("    " + ", ".join(f"0x{x:02X}" for x in blob[k:k + 16]) + ",")
        out.append("};")
        load.append(f"font_blob(font_blob{i}, {first});")
    out.append("#define FONT_LOAD_CHUNKS " + " ".join(load))
    (ROOT / "awto/osd/font_data.inc").write_text("\n".join(out) + "\n")
    words = len(tiles) * 18
    log(f"{len(chars)} chars, {len(tiles)} tiles: {len(data)} B raw -> {sum(len(b) for _, _, b in chunks)} B VLC in {len(chunks)} blob(s); "
        f"font SRAM {words} words ({words * 100 / 12288:.1f} % of 12288) + char map")
    for first, n, blob in chunks:
        assert osd_vlc.decode(blob) == data[first * TILE_BYTES:(first + n) * TILE_BYTES]
    log("round trip: every blob decodes byte-exact")
    if a.png:
        cols = 16
        im = Image.new("L", (cols * (CW + 2), ((len(chars) + cols - 1) // cols) * (CH + 2)), 40)
        for i, ch in enumerate(chars):
            im.paste(Image.fromarray((raster(font, ch) * 85).astype(np.uint8)), ((i % cols) * (CW + 2), (i // cols) * (CH + 2)))
        a.png.parent.mkdir(parents=True, exist_ok=True)
        im.save(a.png)
    return 0


if __name__ == "__main__":
    sys.exit(main())
