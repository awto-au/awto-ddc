#!/usr/bin/env python3
"""Generate awto/gamma/gamma_tab.inc: gamma curves per spec gamma section 5.

e(i) = round_half_up(16368 * (i / 1023) ** (g / gn)), i = 0..1023, g = kind gamma (x10), gn = 2.2 (x10: 22).
Entries 1024 = 0x3FF0, 1025 = 0x0000 (measured, kept from the reference tables).
Each curve: 1026 x 16 bit, big-endian, 2052 bytes. Output is included by awto/gamma/gamma.c.

Usage: python3 -I tools/gen_gamma.py   (log: tmp/logs/gen_gamma.log)
"""
import os
import sys

GAMMA_X10 = (18, 20, 22, 24)   # kind 0..3
GN_X10 = 22                    # panel native gamma 2.2 (measured, spec gamma section 5)
FULL = 16368                   # derived: 0x3FF0 = full scale 1023.0 in 10-bit units, 4 fraction bits
ENTRIES = 1026


def repo_root():
    env = os.environ.get('AWTO_RTDFW_REPO')
    if env:
        return env
    here = os.path.dirname(os.path.abspath(__file__))
    return os.path.dirname(here)


def curve(g_x10):
    ratio = g_x10 / GN_X10
    out = []
    for i in range(1023):
        v = FULL * (i / 1023.0) ** ratio
        out.append(int(v + 0.5))           # round half up (v >= 0)
    out.append(FULL)                       # i = 1023 (formula gives exactly FULL)
    out.append(FULL)                       # entry 1024
    out.append(0)                          # entry 1025
    assert len(out) == ENTRIES
    return out


def main():
    root = repo_root()
    logdir = os.path.join(root, 'tmp', 'logs')
    os.makedirs(logdir, exist_ok=True)
    log = open(os.path.join(logdir, 'gen_gamma.log'), 'w', encoding='utf-8')

    def say(msg):
        print(msg)
        log.write(msg + '\n')

    out_path = os.path.join(root, 'awto', 'gamma', 'gamma_tab.inc')
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    lines = [
        '/* GENERATED by tools/gen_gamma.py (spec gamma section 5). Do not edit. */',
        '/* kind 0..3 = gamma 1.8 / 2.0 / 2.2 / 2.4; R = G = B; 1026 x u16 big-endian per curve. */',
        'static const __code uint8_t gm_tab[4][2052] = {',
    ]
    for kind, g in enumerate(GAMMA_X10):
        vals = curve(g)
        data = []
        for v in vals:
            data.append((v >> 8) & 0xFF)
            data.append(v & 0xFF)
        lines.append('    { /* kind %d: gamma %d.%d */' % (kind, g // 10, g % 10))
        for j in range(0, len(data), 16):
            chunk = ', '.join('0x%02X' % b for b in data[j:j + 16])
            lines.append('        %s,' % chunk)
        lines.append('    },')
        say('kind %d gamma %d.%d: %d entries, e(1)=%d e(1023)=%d' % (kind, g // 10, g % 10, len(vals), vals[1], vals[1023]))
    lines.append('};')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    say('wrote %s' % out_path)
    log.close()
    return 0


if __name__ == '__main__':
    sys.exit(main())
